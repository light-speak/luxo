func TestGeneratedSymbolPreparationFormatsCompleteGoFiles(t *testing.T) {
	for _, values := range []string{"42, 1.2e3, 0xff", "0Xff, 1.2E3, 42", "00i, 42, 0xff"} {
		source := []byte(`// Code generated by luxo. DO NOT EDIT.
package generated
import (
 _ "time" // retain with the right import
 _ "fmt"

 _ "github.com/light-speak/luxo/pkg/lux"
)
var a,b,c = ` + values + "\n")
		want, err := format.Source(source)
		if err != nil {
			t.Fatal(err)
		}
		files := map[string][]byte{"model.gen.go": source}
		if err := prepareGeneratedSymbols(files, false); err != nil {
			t.Fatal(err)
		}
		if got := files["model.gen.go"]; !bytes.Equal(got, want) {
			t.Fatalf("format mismatch\ngot:\n%s\nwant:\n%s", got, want)
		}
	}
}

func TestUnicodeGoIdentifiersAreExportedAndInjective(t *testing.T) {
	seen := make(map[string]string)
	for _, name := range []string{"", "value", "Value", "Éclair", "计数", "数值", "ǅ", "LuxoIdent_", "LuxoIdent_" + hex.EncodeToString([]byte("数值"))} {
		encoded := unicodeGoIdentifier(name)
		if prior, exists := seen[encoded]; exists {
			t.Fatal("distinct source spellings collided", prior, name, encoded)
		}
		seen[encoded] = name
		if name == "value" || name == "Value" || name == "Éclair" || name == "" {
			if encoded != name {
				t.Fatal("unnecessary identifier rewrite", name, encoded)
			}
		} else if !strings.HasPrefix(encoded, goUnicodeIdentifierPrefix) {
			t.Fatal("identifier was not exported", name, encoded)
		}
	}
}

func TestGeneratedUnicodeIdentifiersRetainWireNamesAndComments(t *testing.T) {
	source := "// Code generated by luxo. DO NOT EDIT.\n// 保留业务说明。\npackage generated\ntype 计数 struct { 数值 int64 `json:\"数值\"` }\nfunc read(v 计数) int64 { return v.数值 }\nconst wireName = \"计数.数值\"\n"
	files := map[string][]byte{"unicode.gen.go": []byte(source)}
	if err := prepareGeneratedSymbols(files, true); err != nil {
		t.Fatal(err)
	}
	result := string(files["unicode.gen.go"])
	for _, preserved := range []string{"// Code generated by luxo. DO NOT EDIT.", "// 保留业务说明。", "`json:\"数值\"`", "\"计数.数值\""} {
		if !strings.Contains(result, preserved) {
			t.Fatal("rewriting identifiers changed non-identifier content", preserved, result)
		}
	}
	if !strings.Contains(result, unicodeGoIdentifier("计数")) || !strings.Contains(result, unicodeGoIdentifier("数值")) {
		t.Fatal("declarations or member references were not renamed", result)
	}
	ascii := map[string][]byte{"ascii.gen.go": []byte("// 保留说明\npackage generated\ntype Value struct { ID int64 }\n")}
	want, err := format.Source(ascii["ascii.gen.go"])
	if err != nil {
		t.Fatal(err)
	}
	if err := prepareGeneratedSymbols(ascii, true); err != nil || !bytes.Equal(ascii["ascii.gen.go"], want) {
		t.Fatal("unchanged identifiers must retain the canonical formatting", err)
	}
}

func TestGeneratorRejectsCollidingPackageSymbols(t *testing.T) {
	for _, source := range []string{
		`model User @noTime { id: Int @id } model UserQuery @noTime { id: Int @id }`,
		`model User @noTime { id: Int @id } model UserClient @noTime { id: Int @id }`,
		`model User @noTime { id: Int @id } type UserQuery { id: Int }`,
		`model User @noTime { id: Int @id } type UserFields { id: Int }`,
		`type New { id: Int } api read(): Int { return 42 }`,
		`type App { id: Int } api read(): Int { return 42 }`,
		`type NativeResolver { id: Int } api read(): Int @native`,
		`enum Role { ADMIN } type RoleADMIN { id: Int }`,
		`fn read(): Result<Int> @native api Read(): Int @native`,
		`fn read(value: Int): Result<Int> @native api read(value: String): Int @native`,
		`model User @noTime { id: Int @id } fn read(): Result<User?> @native api read(): User @native`,
	} {
		t.Run(source, func(t *testing.T) {
			input := analyzePermissionFixture(t, source)
			if len(input.Errors) != 0 {
				t.Fatal(input.Errors)
			}
			ids := StableIDs{ModelFields: map[string]map[string]int{}}
			for _, name := range []string{"User", "UserQuery", "UserClient", "UserFields", "New", "App", "NativeResolver", "RoleADMIN"} {
				ids.ModelFields[name] = map[string]int{"id": 1}
			}
			config := GeneratorConfig{IDs: completeFixtureAPIIDs(input, ids)}
			for _, generate := range []func() (*GenerateResult, error){
				func() (*GenerateResult, error) { return Generate(input, "generated", config) },
				func() (*GenerateResult, error) { return mustNewGenerator(t, config).Generate(input, "generated", nil) },
			} {
				output, err := generate()
				if output != nil || err == nil || !strings.Contains(err.Error(), "generated Go symbol") {
					t.Errorf("formal generation accepted conflicting declarations: output=%t err=%v", output != nil, err)
				}
			}
		})
	}
}

func TestGeneratedSymbolValueAndInterfaceConflicts(t *testing.T) {
	for _, sample := range []struct{ body, symbol string }{
		{"type Shared int\nvar Shared int", "Shared"},
		{"const Shared = 1\ntype Shared int", "Shared"},
		{"func Shared() {}\nvar Shared int", "Shared"},
		{"var first, Shared int\nconst Shared = 1", "Shared"},
		{"type Reader interface { Read(); Read() }", "Reader.Read"},
		{"type Reader ((interface { Read(); Read() }))", "Reader.Read"},
	} {
		t.Run(sample.body, func(t *testing.T) {
			err := validateGeneratedSymbols(map[string][]byte{"collision.gen.go": []byte("package generated\n" + sample.body)})
			if err == nil || !strings.Contains(err.Error(), "generated Go symbol \""+sample.symbol+"\"") || !strings.Contains(err.Error(), "collision.gen.go:") {
				t.Fatalf("missing precise collision: %v", err)
			}
		})
	}
}

func TestGeneratedSymbolDiagnosticsAreDeterministic(t *testing.T) {
	files := map[string][]byte{"z.gen.go": []byte("package generated\ntype Shared int"), "a.gen.go": []byte("package generated\nvar Shared int")}
	var first string
	for range 20 {
		err := validateGeneratedSymbols(files)
		if err == nil {
			t.Fatal("cross-file collision was accepted")
		}
		if first == "" {
			first = err.Error()
		} else if first != err.Error() {
			t.Fatal("diagnostic depended on map iteration order", first, err)
		}
	}
	if strings.Index(first, "a.gen.go:") >= strings.Index(first, "z.gen.go:") {
		t.Fatal("collision locations are not stable", first)
	}
}

