func TestGeneratedNativeImplementationReuse(t *testing.T) {
	for _, declaration := range []string{
		`fn read(input: Int): Result<Int> @native api read(value: Int): Int @native`,
		`fn read(input: Int): Int @service @native api read(value: Int): Int @native`,
		`fn read(input: Int): Int @service { return input + 1 } api read(value: Int): Int @native`,
	} {
		t.Run(declaration, func(t *testing.T) {
			call := "read(value)"
			if strings.Contains(declaration, "Result<Int>") {
				call += "?"
			}
			source := declaration
			if !strings.Contains(declaration, "@service") {
				source += "\napi composed(value: Int): Int { return " + call + " }"
			}
			assertions := strings.ReplaceAll(nativeReuseHTTPAssertions, "REGISTER_SERVICE", "")
			var extra []string
			if strings.Contains(declaration, "@service") {
				assertions = strings.ReplaceAll(nativeReuseHTTPAssertions, "REGISTER_SERVICE", "if err:=RegisterServiceFns(router,app);err!=nil{t.Fatal(err)}")
				assertions = strings.ReplaceAll(assertions, `[]string{"read","composed"}`, `[]string{"read"}`)
				rpcAssertions := nativeReuseRPCAssertions
				if !strings.Contains(declaration, "@service @native") {
					rpcAssertions = strings.ReplaceAll(rpcAssertions, "impl.calls.Load()!=before+1", "impl.calls.Load()!=before")
				}
				extra = append(extra, rpcAssertions)
			}
			runGeneratedFixture(t, source, assertions, StableIDs{
				APIs:      map[string]int{"read": 1, "composed": 2, "svc:read": 3},
				APIParams: map[string]map[string]int{"read": {"value": 1}, "composed": {"value": 1}, "svc:read": {"input": 1}},
			}, extra...)
		})
	}
}

