func generateHelpers(modules []moduleInfo) []byte {
	var b bytes.Buffer
	b.Grow(helmHelpersSize(modules))
	b.WriteString(helmCommonHelpers)
	writeHelmPublicConfiguration(&b, modules)
	b.WriteString(helmRolloutAnnotations)
	b.WriteString(helmEnvironmentSources)
	writeHelmJWTEnvironment(&b)

	return b.Bytes()
}

