const (
	helmJWTHeader    = "{{- define \"luxo.jwtEnvironment\" -}}\n{{- with .Values.jwt }}\n{{- with .existingSecret }}\n"
	helmJWTKeyHeader = "- name: "
	helmJWTKeyRef    = "\n  valueFrom:\n    secretKeyRef:\n      name: {{ . | quote }}\n      key: "
	helmJWTOptional  = "      optional: true\n"
	helmJWTEnd       = "{{- end }}\n{{- end }}\n{{- end }}\n"
)

func writeHelmJWTEnvironment(b *bytes.Buffer) {
	b.WriteString(helmJWTHeader)
	for _, key := range jwtDeploymentEnv {
		b.WriteString(helmJWTKeyHeader)
		b.WriteString(key)
		b.WriteString(helmJWTKeyRef)
		b.WriteString(key)
		b.WriteByte('\n')
		if key != "JWT_SECRET" {
			b.WriteString(helmJWTOptional)
		}
	}
	b.WriteString(helmJWTEnd)
}

func writeHelmBackendEnvironment(b *bytes.Buffer, variable, valuesKey string) {
	b.WriteString("            - name: ")
	b.WriteString(variable)
	b.WriteString("\n              {{- with .Values.")
	b.WriteString(valuesKey)
	b.WriteString(".existingSecret }}\n")
	b.WriteString("              valueFrom:\n                secretKeyRef:\n                  name: {{ . | quote }}\n                  key: ")
	b.WriteString(variable)
	b.WriteString("\n              {{- else }}\n              value: {{ required \"set ")
	b.WriteString(valuesKey)
	b.WriteString(".url or ")
	b.WriteString(valuesKey)
	b.WriteString(".existingSecret\" .Values.")
	b.WriteString(valuesKey)
	b.WriteString(".url | quote }}\n              {{- end }}\n")
}

