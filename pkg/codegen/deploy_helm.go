// invalidChartChars matches any character that is not lowercase alphanumeric or hyphen.
var invalidChartChars = regexp.MustCompile(`[^a-z0-9-]`)

// normalizeChartName converts a project name into a valid Helm chart name.
// Chart names must be lowercase RFC 1123 labels: [a-z0-9-], max 53 chars.
func normalizeChartName(name string) string {
	name = strings.ToLower(name)
	name = invalidChartChars.ReplaceAllString(name, "-")
	// Collapse consecutive hyphens
	for strings.Contains(name, "--") {
		name = strings.ReplaceAll(name, "--", "-")
	}
	name = strings.Trim(name, "-")
	if len(name) > 53 {
		name = name[:53]
		name = strings.TrimRight(name, "-")
	}
	if name == "" {
		name = "luxo-app"
	}
	return name
}

// HelmFiles holds generated Helm chart files.
// Keys are relative paths from the chart root (e.g. "Chart.yaml", "templates/gateway-deployment.yaml").
type HelmFiles struct {
	Files map[string][]byte
}

// GenerateHelmFiles produces a complete Helm chart from the semantic result.
// Chart structure:
//
//	deploy/helm/
//	├── Chart.yaml
//	├── values.yaml
//	├── .helmignore
//	└── templates/
//	    ├── _helpers.tpl
//	    ├── configmap.yaml
//	    ├── secret.yaml
//	    ├── serviceaccount.yaml
//	    ├── gateway-deployment.yaml
//	    ├── gateway-service.yaml
//	    ├── ingress.yaml
//	    ├── hpa.yaml
//	    └── module-{name}-deployment.yaml / module-{name}-service.yaml (per module)
func GenerateHelmFiles(result *semantic.Result, projectName string) *HelmFiles {
	modules := collectModules(result)
	var backends helmBackends
	for _, module := range modules {
		backends.legacyEvents = backends.legacyEvents || module.hasEvents
	}
	return renderHelmFiles(modules, projectName, backends)
}

// GenerateHelmFilesChecked produces a Helm chart for explicitly compiled
// adapters. The chart receives remote connection settings at install time.
func GenerateHelmFilesChecked(result *semantic.Result, projectName string, selection EntryBackends) (*HelmFiles, error) {
	if err := validateSemanticResult(result); err != nil {
		return nil, err
	}
	modules, err := selection.validatedModules(result)
	if err != nil {
		return nil, err
	}
	hasCache := backendEnabled(selection.Cache) && modulesNeedCache(modules)
	backends := helmBackends{
		selection: selection,
		nats:      selection.Queue == "nats" || selection.Events == "nats" && slices.ContainsFunc(modules, moduleInfo.usesEventBus),
		redis:     selection.Cache == "redis" && hasCache,
		cache:     hasCache,
	}
	return renderHelmFiles(modules, projectName, backends), nil
}

type helmBackends struct {
	selection    EntryBackends
	nats         bool
	redis        bool
	cache        bool
	legacyEvents bool
}

func renderHelmFiles(modules []moduleInfo, projectName string, backends helmBackends) *HelmFiles {
	if len(modules) == 0 {
		return nil
	}

	projectName = normalizeChartName(projectName)
	gatewayNATS := backends.selection.Events == "nats" && gatewayHasStreams(modules)

	files := make(map[string][]byte)
	files["Chart.yaml"] = generateChartYAML(projectName)
	files["values.yaml"] = generateValuesYAML(modules, projectName, backends)
	files[".helmignore"] = generateHelmIgnore()
	files["templates/_helpers.tpl"] = generateHelpers(modules)
	files["templates/configmap.yaml"] = generateConfigMap(backends.legacyEvents)
	files["templates/secret.yaml"] = generateSecret()
	files["templates/serviceaccount.yaml"] = generateServiceAccount()
	files["templates/gateway-deployment.yaml"] = generateGatewayDeployment(gatewayNATS)
	files["templates/gateway-service.yaml"] = generateGatewayService()
	files["templates/ingress.yaml"] = generateIngress()
	files["templates/hpa.yaml"] = generateHPA(modules)

	for _, m := range modules {
		files[fmt.Sprintf("templates/module-%s-deployment.yaml", m.name)] = generateModuleDeployment(m, backends)
		files[fmt.Sprintf("templates/module-%s-service.yaml", m.name)] = generateModuleService(m)
	}

	return &HelmFiles{Files: files}
}

