// invalidChartChars matches any character that is not lowercase alphanumeric or hyphen.
var invalidChartChars = regexp.MustCompile(`[^a-z0-9-]`)

// normalizeChartName converts a project name into a valid Helm chart name.
// Chart names must be lowercase RFC 1123 labels: [a-z0-9-], max 53 chars.
func normalizeChartName(name string) string {
	name = normalizeHelmLabel(name)
	if len(name) > 53 {
		name = strings.TrimRight(name[:53], "-")
	}
	if name == "" {
		return "luxo-app"
	}
	return name
}

func normalizeHelmLabel(name string) string {
	name = strings.ToLower(name)
	name = invalidChartChars.ReplaceAllString(name, "-")
	// Collapse consecutive hyphens
	for strings.Contains(name, "--") {
		name = strings.ReplaceAll(name, "--", "-")
	}
	return strings.Trim(name, "-")
}

const helmLabelLimit = 63

func isHelmModuleLabel(name string) bool {
	if len(name) == 0 || len(name) > helmLabelLimit || name[0] == '-' || name[len(name)-1] == '-' {
		return false
	}
	for i := range len(name) {
		ch := name[i]
		if ch != '-' && (ch < 'a' || ch > 'z') && (ch < '0' || ch > '9') {
			return false
		}
	}
	return true
}

func planHelmResourceNames(modules []moduleInfo, images deploymentAliases) deploymentAliases {
	for _, module := range modules {
		if !isHelmModuleLabel(images.name(module.name)) {
			return assignHelmResourceNames(modules, images)
		}
	}
	return images
}

func assignHelmResourceNames(modules []moduleInfo, images deploymentAliases) deploymentAliases {
	claimed := make(map[string]bool, len(modules)+1)
	claimed["gateway"] = true
	var normalize []string
	for _, module := range modules {
		name := images.name(module.name)
		if isHelmModuleLabel(name) {
			claimed[name] = true
		} else {
			normalize = append(normalize, module.name)
		}
	}
	// Keep valid labels first. Prefer the shorter original spelling when several normalize to the same label.
	slices.SortFunc(normalize, func(a, b string) int {
		if len(a) != len(b) {
			return len(a) - len(b)
		}
		return strings.Compare(a, b)
	})
	names := make(deploymentAliases, len(images)+len(normalize))
	maps.Copy(names, images)
	for _, module := range normalize {
		name := normalizedHelmModuleLabel(images.name(module))
		for index, base := 2, name; claimed[name]; index++ {
			suffix := "-" + strconv.Itoa(index)
			name = strings.TrimRight(base[:min(len(base), helmLabelLimit-len(suffix))], "-") + suffix
		}
		claimed[name] = true
		names[module] = name
	}
	return names
}

func normalizedHelmModuleLabel(raw string) string {
	name := normalizeHelmLabel(raw)
	if name == "" {
		return "module"
	}
	if len(name) > helmLabelLimit {
		digest := sha256.Sum256([]byte(raw))
		return fmt.Sprintf("%s-%x", strings.TrimRight(name[:helmLabelLimit-17], "-"), digest[:8])
	}
	return name
}

// HelmFiles holds generated Helm chart files.
// Keys are relative paths from the chart root (e.g. "Chart.yaml", "templates/gateway-deployment.yaml").
type HelmFiles struct {
	Files map[string][]byte
}

// HelmGeneratedFileComment marks module templates that the CLI may regenerate or retire.
const HelmGeneratedFileComment = "# Auto-generated by luxo. DO NOT EDIT."

// GenerateHelmFiles produces a complete Helm chart from the semantic result.
// Chart structure:
//
//	deploy/helm/
//	├── Chart.yaml
//	├── values.yaml
//	├── .helmignore
//	└── templates/
//	    ├── _helpers.tpl
//	    ├── configmap.yaml
//	    ├── secret.yaml
//	    ├── serviceaccount.yaml
//	    ├── gateway-deployment.yaml
//	    ├── gateway-service.yaml
//	    ├── ingress.yaml
//	    ├── hpa.yaml
//	    └── module-{name}-deployment.yaml / module-{name}-service.yaml (per module)
func GenerateHelmFiles(result *semantic.Result, projectName string) *HelmFiles {
	modules := collectModules(result)
	var backends helmBackends
	for _, module := range modules {
		backends.legacyEvents = backends.legacyEvents || module.hasEvents
	}
	return renderHelmFiles(modules, projectName, backends)
}

// GenerateHelmFilesChecked produces a Helm chart for explicitly compiled
// adapters. The chart receives remote connection settings at install time.
func GenerateHelmFilesChecked(result *semantic.Result, projectName string, selection EntryBackends) (*HelmFiles, error) {
	if err := validateSemanticResult(result); err != nil {
		return nil, err
	}
	modules, err := selection.validatedModules(result)
	if err != nil {
		return nil, err
	}
	hasCache := backendEnabled(selection.Cache) && modulesNeedCache(modules)
	backends := helmBackends{
		selection: selection,
		nats:      selection.Queue == "nats" || selection.Events == "nats" && slices.ContainsFunc(modules, moduleInfo.usesEventBus),
		redis:     selection.Cache == "redis" && hasCache,
		cache:     hasCache,
	}
	return renderHelmFiles(modules, projectName, backends), nil
}

type helmBackends struct {
	selection    EntryBackends
	nats         bool
	redis        bool
	cache        bool
	legacyEvents bool
}

func renderHelmFiles(modules []moduleInfo, projectName string, backends helmBackends) *HelmFiles {
	if len(modules) == 0 {
		return nil
	}

	projectName = normalizeChartName(projectName)
	gatewayNATS := backends.selection.Events == "nats" && gatewayHasStreams(modules)
	images := planDeploymentAliases(modules, "", "gateway")
	names := planHelmResourceNames(modules, images)

	files := make(map[string][]byte)
	files["Chart.yaml"] = generateChartYAML(projectName)
	files["values.yaml"] = generateValuesYAML(modules, projectName, backends)
	files[".helmignore"] = generateHelmIgnore()
	files["templates/_helpers.tpl"] = generateHelpers(modules, names)
	files["templates/configmap.yaml"] = generateConfigMap(modules, names, backends.legacyEvents)
	files["templates/secret.yaml"] = generateSecret()
	files["templates/serviceaccount.yaml"] = generateServiceAccount()
	files["templates/gateway-deployment.yaml"] = generateGatewayDeployment(gatewayNATS)
	files["templates/gateway-service.yaml"] = generateGatewayService()
	files["templates/ingress.yaml"] = generateIngress()
	files["templates/hpa.yaml"] = generateHPA(modules, names)

	for _, m := range modules {
		resource := names.name(m.name)
		files[fmt.Sprintf("templates/module-%s-deployment.yaml", m.name)] = generateModuleDeployment(m, resource, images.name(m.name), backends)
		files[fmt.Sprintf("templates/module-%s-service.yaml", m.name)] = generateModuleService(m, resource)
	}

	return &HelmFiles{Files: files}
}

