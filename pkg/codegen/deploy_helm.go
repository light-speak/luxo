func generateConfigMap(modules []moduleInfo, names deploymentAliases, hasEvents bool) []byte {
	const natsURL = "  NATS_URL: {{ .Values.nats.url | quote }}\n"
	size := len(helmResourceNamesStart) + len(helmResourceNamesEnd) + len(helmConfigMap)
	for _, module := range modules {
		size += len(names.name(module.name)) + len(` ""`)
	}
	if hasEvents {
		size += len(natsURL)
	}
	var b bytes.Buffer
	b.Grow(size)
	b.WriteString(helmResourceNamesStart)
	for _, module := range modules {
		b.WriteString(` "`)
		b.WriteString(names.name(module.name))
		b.WriteByte('"')
	}
	b.WriteString(helmResourceNamesEnd)
	b.WriteString(helmConfigMap)
	if hasEvents {
		b.WriteString(natsURL)
	}
	return b.Bytes()
}

