func writeHelmPublicConfiguration(b *bytes.Buffer, modules []moduleInfo, names deploymentAliases) {
	// The template file's unnamed body is the public ConfigMap data and Pod
	// checksum input. Keep credential-bearing URLs and Secrets out of it.
	b.WriteString(helmPublicConfigurationHeader)
	for _, module := range modules {
		b.WriteString(strings.ToUpper(module.name))
		b.WriteString(helmServiceAddressHeader)
		b.WriteString(names.name(module.name))
		b.WriteString(helmServiceAddressPort)
		b.WriteString(module.name)
		b.WriteString(helmServiceAddressEnd)
	}
	b.WriteByte('\n')
}

// helmHelpersSize accounts for the static definitions and the emitted names.
// Reserving the complete output avoids recopying the shared chart helpers.
func helmHelpersSize(modules []moduleInfo, names deploymentAliases) int {
	size := len(helmCommonHelpers) + len(helmPublicConfigurationHeader) + 1 +
		len(helmRolloutAnnotations) + len(helmEnvironmentSources) + len(helmJWTHeader) + len(helmJWTEnd)
	for _, module := range modules {
		size += len(module.name) + len(names.name(module.name)) + len(helmServiceAddressHeader) + len(helmServiceAddressPort) + len(helmServiceAddressEnd)
		for _, r := range module.name {
			size += utf8.RuneLen(unicode.ToUpper(r))
		}
	}
	for _, key := range jwtDeploymentEnv {
		size += len(helmJWTKeyHeader) + len(helmJWTKeyRef) + 2*len(key) + 1
		if key != "JWT_SECRET" {
			size += len(helmJWTOptional)
		}
	}
	return size
}

