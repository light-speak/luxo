func TestGenerateOutputIsGofmtFormatted(t *testing.T) {
	SetModelFieldIDs(map[string]map[string]int{
		"User":        {"id": 1, "name": 2, "role": 3, "createdAt": 4, "bio": 5},
		"AuthPayload": {"token": 1, "user": 2},
	})
	defer SetModelFieldIDs(nil)

	file := &ast.File{
		Name: "origin/auth/test.luxo",
		Enums: []*ast.EnumDecl{
			{Name: "Role", Values: []string{"USER", "ADMIN"}},
		},
		Models: []*ast.ModelDecl{
			{
				Name:       "User",
				Directives: []*ast.Directive{{Name: "crud"}},
				Fields: []*ast.FieldDecl{
					{Name: "id", Type: &ast.TypeRef{Name: "Int"}, Directives: []*ast.Directive{{Name: "id"}, {Name: "auto"}}},
					{Name: "name", Type: &ast.TypeRef{Name: "String"}},
					{Name: "role", Type: &ast.TypeRef{Name: "Role"}},
					{Name: "createdAt", Type: &ast.TypeRef{Name: "DateTime"}},
					{Name: "bio", Type: &ast.TypeRef{Name: "String", Nullable: true}},
				},
			},
		},
		Types: []*ast.TypeDecl{
			{
				Name: "AuthPayload",
				Fields: []*ast.FieldDecl{
					{Name: "token", Type: &ast.TypeRef{Name: "String"}},
					{Name: "user", Type: &ast.TypeRef{Name: "User"}},
				},
			},
		},
		APIs: []*ast.ApiDecl{
			{
				Name:       "whoAmI",
				Directives: []*ast.Directive{{Name: "native"}},
				ReturnType: &ast.TypeRef{Name: "AuthPayload"},
			},
		},
	}

	gr := Generate(result(file), "gen", DriverPG)
	if len(gr.Files) == 0 {
		t.Fatal("no files generated")
	}
	for name, src := range gr.Files {
		formatted, err := format.Source(src)
		if err != nil {
			t.Errorf("%s: generated code does not parse: %v", name, err)
			continue
		}
		if !bytes.Equal(formatted, src) {
			t.Errorf("%s: output is not gofmt-formatted", name)
		}
	}
}

