// buildResult creates a semantic.Result from manually constructed AST.
func buildResult(files ...*ast.File) *semantic.Result {
	return &semantic.Result{
		Files: files,
	}
}

// collapseSpaces normalizes runs of spaces/tabs to single spaces so assertions
// are insensitive to gofmt struct-field alignment.
func collapseSpaces(s string) string {
	var b strings.Builder
	b.Grow(len(s))
	inSpace := false
	for _, r := range s {
		if r == ' ' || r == '\t' {
			inSpace = true
			continue
		}
		if inSpace {
			b.WriteByte(' ')
			inSpace = false
		}
		b.WriteRune(r)
	}
	return b.String()
}

