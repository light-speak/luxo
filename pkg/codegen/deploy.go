// DeployFiles holds generated deployment configuration files.
type DeployFiles struct {
	Dockerfile    []byte
	DockerCompose []byte
}

var jwtDeploymentEnv = [...]string{"JWT_SECRET", "JWT_EXPIRES", "JWT_REFRESH", "JWT_REFRESH_EXPIRES"}

// GenerateDeployFiles produces Dockerfile and docker-compose.yml
// from the semantic result. Auto-detects modules, dependencies, and infra needs.
func GenerateDeployFiles(result *semantic.Result, projectName string) *DeployFiles {
	modules := collectModules(result)
	var backends composeBackends
	backends.legacyRedis = true
	for _, module := range modules {
		backends.legacyNATS = backends.legacyNATS || module.hasEvents
	}
	return renderDeployFiles(modules, projectName, backends)
}

// GenerateDeployFilesChecked produces Compose files for the same explicit
// backend selection used to generate the cluster entry points.
func GenerateDeployFilesChecked(result *semantic.Result, projectName string, selection EntryBackends) (*DeployFiles, error) {
	if err := validateSemanticResult(result); err != nil {
		return nil, err
	}
	modules, err := selection.validatedModules(result)
	if err != nil {
		return nil, err
	}
	return renderDeployFiles(modules, projectName, composeBackends{selection: selection}), nil
}

type composeBackends struct {
	selection   EntryBackends
	legacyNATS  bool
	legacyRedis bool
}

const (
	composeNATSURL               = "nats://nats:4222"
	composeJetStreamReadinessEnv = "LUXO_INTERNAL_COMPOSE_JETSTREAM"
)

type composeModuleNames struct {
	modules  []moduleInfo
	services deploymentAliases
	stages   deploymentAliases
}

const composeCacheSettings = `      LUXO_CACHE_PROJECT: "${LUXO_CACHE_PROJECT:?set LUXO_CACHE_PROJECT}"
      LUXO_CACHE_ENVIRONMENT: "${LUXO_CACHE_ENVIRONMENT:?set LUXO_CACHE_ENVIRONMENT}"
      LUXO_CACHE_REVISION: "${LUXO_CACHE_REVISION:?set LUXO_CACHE_REVISION}"
      LUXO_CACHE_ORIGIN_CONCURRENCY: "${LUXO_CACHE_ORIGIN_CONCURRENCY:?set LUXO_CACHE_ORIGIN_CONCURRENCY}"
      LUXO_CACHE_ORIGIN_MAX_WAITERS: "${LUXO_CACHE_ORIGIN_MAX_WAITERS:?set LUXO_CACHE_ORIGIN_MAX_WAITERS}"
      LUXO_CACHE_ORIGIN_WAIT_TIMEOUT: "${LUXO_CACHE_ORIGIN_WAIT_TIMEOUT:?set LUXO_CACHE_ORIGIN_WAIT_TIMEOUT}"
`

func renderDeployFiles(modules []moduleInfo, projectName string, backends composeBackends) *DeployFiles {
	if len(modules) == 0 {
		return nil
	}

	stages := planDeploymentAliases(modules, "-run", "builder", "gateway", "gateway-run")
	return &DeployFiles{
		Dockerfile:    generateDockerfile(modules, stages),
		DockerCompose: generateDockerCompose(modules, projectName, backends, stages),
	}
}

func generateDockerfile(modules []moduleInfo, stages deploymentAliases) []byte {
	var b strings.Builder

	b.WriteString("# Auto-generated by luxo. DO NOT EDIT.\n")
	b.WriteString("FROM golang:" + generatedGoVersion + "-alpine AS builder\n")
	b.WriteString("WORKDIR /app\n")
	b.WriteString("COPY go.mod go.sum ./\n")
	// A project without migrations still needs a directory in the runtime image.
	b.WriteString("RUN go mod download && mkdir -p /app/migrations\n")
	b.WriteString("COPY . .\n\n")

	// Per-module build stages
	for _, m := range modules {
		fmt.Fprintf(&b, "FROM builder AS %s\n", stages.name(m.name))
		fmt.Fprintf(&b, "RUN CGO_ENABLED=0 go build -o /service ./%s/\n\n", ModuleEntryDirectory(m.name))
	}

	// Gateway build
	b.WriteString("FROM builder AS gateway\n")
	b.WriteString("RUN CGO_ENABLED=0 go build -o /service ./lucis/gateway/\n\n")

	// Runtime images — include migrations for auto-migrate on startup
	for _, m := range modules {
		stage := stages.name(m.name)
		fmt.Fprintf(&b, "FROM alpine:3.20 AS %s-run\n", stage)
		fmt.Fprintf(&b, "WORKDIR /app\n")
		fmt.Fprintf(&b, "COPY --from=%s /service /usr/local/bin/service\n", stage)
		fmt.Fprintf(&b, "COPY --from=builder /app/migrations/ /app/migrations/\n")
		fmt.Fprintf(&b, "ENTRYPOINT [\"service\"]\n\n")
	}

	b.WriteString("FROM alpine:3.20 AS gateway-run\n")
	b.WriteString("COPY --from=gateway /service /usr/local/bin/service\n")
	b.WriteString("ENTRYPOINT [\"service\"]\n")

	return []byte(b.String())
}

func generateDockerCompose(modules []moduleInfo, projectName string, backends composeBackends, stages deploymentAliases) []byte {
	var b bytes.Buffer
	queueNATS := backends.selection.Queue == "nats"
	eventNATS := backends.selection.Events == "nats"
	cacheRedis := backends.selection.Cache == "redis"
	gatewayNATS := eventNATS && gatewayHasStreams(modules)
	var cacheBytes int
	if backendEnabled(backends.selection.Cache) {
		for _, module := range modules {
			if module.hasCache {
				cacheBytes += len(composeCacheSettings)
			}
		}
		b.Grow(cacheBytes)
	}

	b.WriteString("# Auto-generated by luxo. DO NOT EDIT.\n")
	b.WriteString("services:\n")
	system := [4]string{"postgres", "gateway"}
	reserved := system[:2]
	writeComposePostgres(&b, projectName)
	if backends.legacyNATS || queueNATS || eventNATS && slices.ContainsFunc(modules, moduleInfo.usesEventBus) {
		writeComposeNATS(&b, projectName, queueNATS, backends.legacyNATS)
		reserved = append(reserved, "nats")
	}
	if backends.legacyRedis || cacheRedis && cacheBytes > 0 {
		writeComposeRedis(&b, projectName, backends.legacyRedis)
		reserved = append(reserved, "redis")
	}
	names := composeModuleNames{modules: modules, services: planDeploymentAliases(modules, "", reserved...), stages: stages}
	for _, module := range modules {
		writeComposeModule(&b, module, projectName, backends, names)
	}
	writeComposeGateway(&b, names, gatewayNATS)
	b.WriteString("volumes:\n")
	b.WriteString("  pgdata:\n")
	if queueNATS {
		b.WriteString("  natsdata:\n")
	}
	return b.Bytes()
}

func writeComposePostgres(b *bytes.Buffer, projectName string) {
	b.WriteString("  postgres:\n")
	b.WriteString("    image: postgres:17-alpine\n")
	fmt.Fprintf(b, "    container_name: %s-pg\n", projectName)
	b.WriteString("    restart: always\n")
	b.WriteString("    environment:\n")
	b.WriteString("      POSTGRES_USER: ${DATABASE_USER:-postgres}\n")
	b.WriteString("      POSTGRES_PASSWORD: ${DATABASE_PASSWORD:-postgres}\n")
	b.WriteString("    volumes:\n")
	b.WriteString("      - pgdata:/var/lib/postgresql/data\n")
	b.WriteString("    healthcheck:\n")
	b.WriteString("      test: [\"CMD-SHELL\", \"pg_isready -U ${DATABASE_USER:-postgres}\"]\n")
	b.WriteString("      interval: 5s\n")
	b.WriteString("      timeout: 3s\n")
	b.WriteString("      retries: 5\n\n")
}

func writeComposeNATS(b *bytes.Buffer, projectName string, queue, legacy bool) {
	b.WriteString("  nats:\n")
	b.WriteString("    image: nats:2-alpine\n")
	fmt.Fprintf(b, "    container_name: %s-nats\n", projectName)
	b.WriteString("    restart: always\n")
	switch {
	case queue:
		b.WriteString("    command: [\"-js\", \"-sd\", \"/data\", \"-m\", \"8222\"]\n")
		b.WriteString("    volumes:\n      - natsdata:/data\n")
		writeComposeHealthcheck(b, `["CMD", "wget", "-q", "-O", "/dev/null", "http://127.0.0.1:8222/healthz?js-enabled-only=true"]`)
	case !legacy:
		b.WriteString("    command: [\"-m\", \"8222\"]\n")
		writeComposeHealthcheck(b, `["CMD", "wget", "-q", "-O", "/dev/null", "http://127.0.0.1:8222/healthz"]`)
	}
	b.WriteString("\n")
}

func writeComposeRedis(b *bytes.Buffer, projectName string, legacy bool) {
	b.WriteString("  redis:\n")
	b.WriteString("    image: redis:7-alpine\n")
	fmt.Fprintf(b, "    container_name: %s-redis\n", projectName)
	b.WriteString("    restart: always\n")
	if !legacy {
		writeComposeHealthcheck(b, `["CMD", "redis-cli", "ping"]`)
	}
	b.WriteString("\n")
}

func writeComposeHealthcheck(b *bytes.Buffer, command string) {
	b.WriteString("    healthcheck:\n      test: ")
	b.WriteString(command)
	b.WriteString("\n      interval: 5s\n      timeout: 3s\n      retries: 5\n")
}

func writeComposeModule(b *bytes.Buffer, module moduleInfo, projectName string, backends composeBackends, names composeModuleNames) {
	queueNATS := backends.selection.Queue == "nats"
	nats := queueNATS || backends.selection.Events == "nats" && module.usesEventBus()
	cache := backendEnabled(backends.selection.Cache) && module.hasCache
	redis := cache && backends.selection.Cache == "redis"
	fmt.Fprintf(b, "  %s:\n    build: { context: ., target: %s-run }\n", names.services.name(module.name), names.stages.name(module.name))
	b.WriteString("    restart: always\n")
	b.WriteString("    environment:\n")
	b.WriteString("      DATABASE_DRIVER: pg\n")
	b.WriteString("      DATABASE_HOST: postgres\n")
	b.WriteString("      DATABASE_PORT: \"5432\"\n")
	b.WriteString("      DATABASE_USER: ${DATABASE_USER:-postgres}\n")
	b.WriteString("      DATABASE_PASSWORD: ${DATABASE_PASSWORD:-postgres}\n")
	fmt.Fprintf(b, "      DATABASE_PREFIX: %s\n", projectName)
	b.WriteString("      APP_PORT: \"4000\"\n")
	b.WriteString("      LUXO_PORT: \"9000\"\n")
	if nats || backends.legacyNATS {
		b.WriteString("      NATS_URL: " + composeNATSURL + "\n")
	}
	if queueNATS {
		b.WriteString("      " + composeJetStreamReadinessEnv + ": \"1\"\n")
	}
	if redis {
		b.WriteString("      REDIS_URL: redis://redis:6379\n")
	}
	if cache {
		b.WriteString(composeCacheSettings)
	}
	if module.hasLoaders && module.hasExtend {
		names.writeRPCAddresses(b, module.name)
	}
	writeComposeJWTEnvironment(b)
	b.WriteString("    depends_on:\n")
	b.WriteString("      postgres: { condition: service_healthy }\n")
	if nats {
		b.WriteString("      nats: { condition: service_healthy }\n")
	}
	if redis {
		b.WriteString("      redis: { condition: service_healthy }\n")
	}
	b.WriteString("\n")
}

func writeComposeGateway(b *bytes.Buffer, names composeModuleNames, nats bool) {
	b.WriteString("  gateway:\n")
	b.WriteString("    build: { context: ., target: gateway-run }\n")
	b.WriteString("    restart: always\n")
	b.WriteString("    ports:\n")
	b.WriteString("      - \"${GATEWAY_PORT:-4000}:4000\"\n")
	b.WriteString("    environment:\n")
	b.WriteString("      APP_PORT: \"4000\"\n")
	b.WriteString("      CORS_ORIGIN: \"${CORS_ORIGIN:-*}\"\n")
	if nats {
		b.WriteString("      NATS_URL: " + composeNATSURL + "\n")
	}
	names.writeRPCAddresses(b, "")
	writeComposeJWTEnvironment(b)
	b.WriteString("    depends_on:\n")
	if nats {
		b.WriteString("      nats: { condition: service_healthy }\n")
	}
	for _, m := range names.modules {
		fmt.Fprintf(b, "      %s: { condition: service_started }\n", names.services.name(m.name))
	}
	b.WriteString("\n")
}

// Keep the logical environment key used by generated RPC clients. Only renamed
// services need an explicit default address instead of the logical DNS name.
func (names composeModuleNames) writeRPCAddresses(b *bytes.Buffer, exclude string) {
	if len(names.services) == 0 {
		return
	}
	for _, module := range names.modules {
		if alias := names.services[module.name]; alias != "" && module.name != exclude {
			key := strings.ToUpper(module.name) + "_SERVICE_ADDR"
			fmt.Fprintf(b, "      %[1]s: \"${%[1]s:-%[2]s:9000}\"\n", key, alias)
		}
	}
}

func writeComposeJWTEnvironment(b *bytes.Buffer) {
	// Compose inherits null-valued entries and leaves absent variables unset.
	for _, key := range jwtDeploymentEnv {
		b.WriteString("      ")
		b.WriteString(key)
		b.WriteString(":\n")
	}
}
