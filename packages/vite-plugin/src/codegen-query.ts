import type { LuxoSchema } from '@luxojs/client'

const comparisons = ['eq', 'ne', 'gt', 'gte', 'lt', 'lte']
const patterns = ['eq', 'ne', 'contains', 'startswith', 'endswith', 'match']

function identifier(name: string): void {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error(`invalid query identifier: ${name}`)
}

function fieldType(type: string, schema: LuxoSchema): { name: string; value: string; operators: string[] } {
  if (Object.hasOwn(schema.enums ?? {}, type)) {
    identifier(type)
    return { name: `Models.${type}`, value: `enumRawValue(value, ${JSON.stringify(type)})`, operators: ['eq', 'ne'] }
  }
  switch (type) {
    case 'Int': return { name: 'bigint', value: 'value', operators: comparisons }
    case 'Float': return { name: 'number', value: 'value', operators: comparisons }
    case 'Boolean': return { name: 'boolean', value: 'value', operators: ['eq', 'ne'] }
    case 'String': return { name: 'string', value: 'value', operators: patterns }
    case 'UUID': return { name: 'string', value: 'value', operators: ['eq', 'ne'] }
    case 'DateTime': case 'Decimal': return { name: 'string', value: 'value', operators: comparisons }
    default: throw new Error(`unsupported query type: ${type}`)
  }
}

export function genQueryBuilders(schema: LuxoSchema): string {
  let out = '// Code generated by luxo. DO NOT EDIT.\n'
  const queries = Object.values(schema.apis).filter(api => !api.internal && api.query).map(api => api.query!)
  const types: string[] = []
  if (queries.some(query => query.filters?.length)) types.push('Filter')
  if (queries.some(query => query.sorters?.length)) types.push('Sorter')
  if (types.length) out += `import type { ${types.join(', ')} } from '@luxojs/client'\n`
  if (queries.some(query => query.filters?.some(field => Object.hasOwn(schema.enums ?? {}, field.type)))) {
    out += "import { enumRawValue } from '@luxojs/client'\nimport type * as Models from './types.js'\n"
  }
  for (const api of Object.values(schema.apis)) {
    if (api.internal || !api.query) continue
    identifier(api.name)
    const generatedName = `LuxoQuery_${api.name}`
    if (Object.hasOwn(schema.models, generatedName) || Object.hasOwn(schema.types ?? {}, generatedName) || Object.hasOwn(schema.enums ?? {}, generatedName)) {
      throw new Error(`query builder conflicts with declared type: ${generatedName}`)
    }
    if (!api.paginated || api.stream) throw new Error(`query controls require a paginated unary API: ${api.name}`)
    const names = new Set<string>()
    out += `export const LuxoQuery_${api.name} = {\n`
    for (const field of api.query.filters ?? []) {
      identifier(field.field)
      if (names.has(field.field)) throw new Error(`duplicate query field: ${field.field}`)
      names.add(field.field)
      const type = fieldType(field.type, schema)
      const seen = new Set<string>()
      if (!field.operators.length) throw new Error(`empty query operators: ${field.field}`)
      for (const op of field.operators) {
        if (!type.operators.includes(op) || seen.has(op)) throw new Error(`invalid query operator: ${op}`)
        seen.add(op)
        out += `  ${field.field}_${op}(value: ${type.name}): Filter { return { field: ${JSON.stringify(field.field)}, op: '${op}', value: ${type.value} } },\n`
      }
    }
    names.clear()
    for (const field of api.query.sorters ?? []) {
      identifier(field)
      if (names.has(field)) throw new Error(`duplicate sorter field: ${field}`)
      names.add(field)
      for (const order of ['asc', 'desc']) {
        out += `  ${field}_${order}(): Sorter { return { field: ${JSON.stringify(field)}, order: '${order}' } },\n`
      }
    }
    out += '} as const\n\n'
  }
  return out
}
