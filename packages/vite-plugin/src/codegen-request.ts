import type { LuxoAPI, LuxoField, LuxoParam, LuxoSchema } from '@luxojs/client'
import { isScalar, luxoTypeToTS } from './codegen-response'

type Field = LuxoField | LuxoParam
type InputName = (name: string) => string
export const requestClass = (api: LuxoAPI): string => `$${api.name}Request`

export function genRequests(schema: LuxoSchema, inputName: InputName, staticEncoding = false): string {
  const apis = Object.values(schema.apis).filter(api => !api.internal)
  let out = '// Generated by Luxo. DO NOT EDIT.\n\n'
  out += "import { GeneratedRequest, Encoder, enumRawValue, stringFromJSON, booleanFromJSON, encodeJSONParam, utf8Length } from '@luxojs/client'\n"
  out += `import type { Filter, Sorter, PreparedSelection${staticEncoding ? ', RequestEncoder' : ''} } from '@luxojs/client'\nimport type * as Types from './types.js'\n\n`
  for (const api of apis) out += genRequest(api, schema, inputName, staticEncoding)
  const used = new Set<string>()
  const visit = (field: Field): void => {
    if (field.type !== 'Model') return
    const name = field.typeName ?? ''
    if (used.has(name)) return
    const model = schema.types?.[name] ?? schema.models[name]
    if (!model) throw new Error(`missing input type ${name}`)
    used.add(name)
    for (const nested of model.fields) visit(nested)
  }
  for (const api of apis) for (const param of api.params ?? []) visit(param)
  for (const name of used) out += genInput(name, schema, inputName)
  return out
}

function fieldType(field: Field, schema: LuxoSchema, inputName: InputName): string {
  const name = field.typeName ?? field.type
  let type = schema.enums?.[name] ? `Types.${name}`
    : field.type === 'Model' ? `Types.${inputName(name)}` : luxoTypeToTS(field.type)
  if (field.isList || ('list' in field && field.list)) type += '[]'
  return field.nullable ? `${type} | null` : type
}

function genRequest(api: LuxoAPI, schema: LuxoSchema, inputName: InputName, staticEncoding: boolean): string {
  const params = api.params ?? []
  const fields = params.map(p => `${JSON.stringify(p.name)}${p.hasDefault || (api.paginated && ['page', 'pageSize'].includes(p.name)) ? '?' : ''}: ${fieldType(p, schema, inputName)}`)
  fields.push('$select?: string | PreparedSelection', '$filters?: Filter[]', '$sorters?: Sorter[]')
  if (staticEncoding) {
    let out = `export const ${requestClass(api)}: RequestEncoder<{ ${fields.join('; ')} }> = {\n  apiID: ${api.id},\n`
    out += capacityHint(api, true)
    out += '  writeParameters(enc, values): void {\n'
    for (const param of params) out += writeField(param, `values?.[${JSON.stringify(param.name)}]`, true, true)
    return out + '  },\n}\n\n'
  }
  let out = `export class ${requestClass(api)} extends GeneratedRequest {\n  readonly apiID = ${api.id}\n`
  out += `  private readonly values: { ${fields.join('; ')} } | undefined\n`
  out += `  constructor(values?: { ${fields.join('; ')} }) { super(); this.values = values }\n`
  out += capacityHint(api)
  out += '  override get selection(): string | PreparedSelection | undefined { return this.values?.$select }\n'
  out += '  override get filters(): readonly Filter[] | undefined { return this.values?.$filters }\n'
  out += '  override get sorters(): readonly Sorter[] | undefined { return this.values?.$sorters }\n'
  out += '  toJSONParameters(): { [key: string]: unknown } { return this.values ?? {} }\n'
  out += '  writeParameters(enc: Encoder): void {\n'
  for (const param of params) out += writeField(param, `this.values?.[${JSON.stringify(param.name)}]`, true)
  return out + '  }\n}\n\n'
}

function capacityHint(api: LuxoAPI, staticEncoding = false): string {
  const params = api.params ?? []
  const fixed = new Set(['Int', 'Duration', 'Float', 'Boolean', 'UUID', 'DateTime', 'Bytes'])
  const signature = staticEncoding ? 'initialCapacity(values): number' : 'override get initialCapacity(): number'
  const end = staticEncoding ? ',' : ''
  if (staticEncoding && params.length > 4 && params.every(p => !p.isList && fixedWireSize[p.type] !== undefined)) {
    return `  initialCapacity(): number { return ${fixedCapacity(api, params, 1024)} },\n`
  }
  if (params.length > 4 || params.some(p => p.isList || !fixed.has(p.type))) {
    return staticEncoding ? '  initialCapacity(): number { return 1024 },\n' : ''
  }
  const bytes = params.filter(p => p.type === 'Bytes')
  if (bytes.length === 0) return `  ${staticEncoding ? 'initialCapacity(): number' : signature} { return ${fixedCapacity(api, params)} }${end}\n`
  let out = `  ${signature} {\n    let size = 64\n`
  for (const [index, param] of bytes.entries()) {
    out += `    const value${index} = ${staticEncoding ? 'values' : 'this.values'}?.[${JSON.stringify(param.name)}]\n`
    out += `    if (value${index} instanceof Uint8Array) size += Math.min(value${index}.byteLength, 65536)\n`
  }
  return out + `    return Math.min(size, 65536)\n  }${end}\n`
}

const fixedWireSize: Readonly<Record<string, number>> = {
  Int: 10, Duration: 10, Float: 8, Boolean: 1, UUID: 16, DateTime: 18,
}

/** Account for the encoder's maximum write reservation, not just the final byte count. */
function fixedCapacity(api: LuxoAPI, params: LuxoParam[], limit = 64): number {
  if (!api.returnType || !isScalar(api.returnType)) return 64
  const ids = [api.id, ...params.map(param => param.id)]
  if (ids.some(id => !Number.isSafeInteger(id) || id < 1 || id > 2147483647)) return 64
  const width = (id: number): number => Math.ceil(Math.log2(id + 1) / 7)
  let cursor = width(api.id) + 1
  let required = Math.max(cursor, api.id < 128 ? 1 : 8)
  for (const param of params) {
    const valueSize = fixedWireSize[param.type]
    if (valueSize === undefined) return 64
    required = Math.max(required, cursor + (param.id < 128 ? 1 : 8))
    cursor += width(param.id) + (param.nullable ? 1 : 0) + valueSize
    required = Math.max(required, cursor)
  }
  return Math.min(limit, Math.max(16, 2 ** Math.ceil(Math.log2(Math.max(required, cursor + 1)))))
}

function writeField(field: Field, expression: string, parameter: boolean, staticEncoding = false): string {
  let out = `    { const value = ${expression}\n      if (value !== undefined) {\n        enc.writeVarint(${field.id})\n`
  if (field.nullable) out += '        if (value === null) { enc.writeBool(false) } else {\n          enc.writeBool(true)\n'
  else out += `        if (value === null) throw new TypeError(${JSON.stringify(`${field.name} is not nullable`)})\n`
  if (field.isList || ('list' in field && field.list)) {
    out += `        if (!Array.isArray(value)) throw new TypeError(${JSON.stringify(`${field.name} must be a list`)})\n`
    out += '        enc.writeVarint(value.length)\n        for (const item of value) {\n'
    out += writeValue(field, 'item', parameter, staticEncoding)
    out += '        }\n'
  } else out += writeValue(field, 'value', parameter, staticEncoding)
  if (field.nullable) out += '        }\n'
  return out + '      }\n    }\n'
}

function writeValue(field: Field, value: string, parameter: boolean, staticEncoding: boolean): string {
  const statements: Record<string, string> = {
    Int: `enc.writeSvarint(${value})`, Duration: `enc.writeSvarint(${value})`,
    Float: `enc.writeFixed64(${value})`, Boolean: `enc.writeBool(booleanFromJSON(${value}))`,
    String: `enc.writeString(stringFromJSON(${value}))`, Decimal: `enc.writeString(stringFromJSON(${value}))`,
    Enum: `enc.writeString(enumRawValue(${value}, ${JSON.stringify(field.typeName)}))`,
    UUID: `enc.writeUUID(${value})`, DateTime: `enc.writeDateTime(${value})`,
    JSON: `enc.writeBytes(encodeJSONParam(${value}))`,
    Bytes: `if (!(${value} instanceof Uint8Array)) throw new TypeError('Bytes requires Uint8Array'); enc.writeBytes(${value})`,
  }
  if (field.type === 'Model') {
    if (parameter && staticEncoding) return `          enc.writeDelimitedValue(${value}, write$${field.typeName})\n`
    const call = `write$${field.typeName}(enc, ${value})`
    return `          ${parameter ? `enc.writeDelimited(enc => ${call})` : call}\n`
  }
  const statement = statements[field.type]
  if (!statement) throw new Error(`unsupported static request type ${field.type}`)
  return `          ${statement}\n`
}

function genInput(name: string, schema: LuxoSchema, inputName: InputName): string {
  const model = schema.types?.[name] ?? schema.models[name]
  let out = `function write$${name}(enc: Encoder, value: Types.${inputName(name)}): void {\n`
  out += `  if (typeof value !== 'object' || value === null) throw new TypeError(${JSON.stringify(`${name} must be an object`)})\n`
  const arena = model.fields.filter(f => !f.isList && !f.list && ['String', 'Enum'].includes(f.type)).map(f => {
    const value = `value[${JSON.stringify(f.name)}]`
    const text = f.type === 'Enum' ? `enumRawValue(${value}, ${JSON.stringify(f.typeName)})` : `stringFromJSON(${value})`
    return `(${value} == null ? 0 : utf8Length(${text}))`
  })
  out += `  enc.writeVarint(${arena.join(' + ') || '0'})\n`
  // Keep the source object outside the scoped per-field local named value.
  out += '  const source = value\n'
  for (const field of model.fields) out += writeField(field, `source[${JSON.stringify(field.name)}]`, false)
  return out + '  enc.writeEnd()\n}\n\n'
}
