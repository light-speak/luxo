import { writeFileSync, mkdirSync, existsSync } from 'fs'
import { join } from 'path'
import type { LuxoSchema, LuxoAPI, LuxoModel, LuxoField } from '@luxojs/client'

/** Generate TypeScript types + client from Luxo schema */
export async function generateTypes(schema: LuxoSchema, outDir: string): Promise<void> {
  if (!existsSync(outDir)) {
    mkdirSync(outDir, { recursive: true })
  }

  writeFileSync(join(outDir, 'types.ts'), genTypes(schema))
  writeFileSync(join(outDir, 'schema.ts'), genSchema(schema))
  writeFileSync(join(outDir, 'client.ts'), genClient(schema))
  console.log(`[luxo] Generated types → ${outDir}/`)
}

function luxoTypeToTS(type: string): string {
  switch (type) {
    case 'Int': case 'Float': case 'Duration': return 'number'
    case 'String': case 'DateTime': case 'UUID': case 'Decimal': case 'Enum': return 'string'
    case 'Boolean': return 'boolean'
    case 'Bytes': return 'Uint8Array'
    case 'JSON': return 'unknown'
    default: return type // model reference
  }
}

// --- types.ts ---

/** Resolve field type to TypeScript, using typeName for model/enum references */
function resolveFieldType(field: { type: string; typeName?: string; isList?: boolean; list?: boolean }, schema: LuxoSchema): string {
  const isList = field.isList || field.list
  const typeName = field.typeName || field.type
  let ts: string

  // Check if it's an enum
  if (schema.enums?.[typeName]) {
    ts = typeName
  } else if (schema.models[typeName]) {
    ts = typeName // model reference
  } else if (schema.types?.[typeName]) {
    ts = typeName // type declaration reference
  } else {
    ts = luxoTypeToTS(field.type)
  }

  return isList ? `${ts}[]` : ts
}

function genTypes(schema: LuxoSchema): string {
  let out = '// Auto-generated by @luxo/vite-plugin. DO NOT EDIT.\n\n'
  out += "import type { Page } from '@luxojs/client'\n"
  const runtimeImports = ['Decoder', 'ColumnarDecoder']
  const fields = [
    ...Object.values(schema.models).flatMap(model => model.fields),
    ...Object.values(schema.types ?? {}).flatMap(type => type.fields),
  ]
  if (fields.some(field => field.type === 'Bytes')) runtimeImports.push('decodeBase64')
  if (fields.some(field => field.type === 'JSON')) runtimeImports.push('decodeJSONValue')
  if (fields.some(field => (field.isList || field.list) && !isNestedField(field, schema))) runtimeImports.push('decodeScalarArray')
  if (fields.some(field => field.type === 'DateTime' && (field.isList || field.list))) runtimeImports.push('unixSecondsToISO')
  out += `import { ${runtimeImports.join(', ')} } from '@luxojs/client'\n\n`

  // Enum types — union of string literals
  if (schema.enums) {
    for (const e of Object.values(schema.enums)) {
      const values = e.values.map((v: string) => `'${v}'`).join(' | ')
      out += `export type ${e.name} = ${values}\n`
      out += `export const ${e.name}Values = [${e.values.map((v: string) => `'${v}'`).join(', ')}] as const\n\n`
    }
  }

  // Type declarations (non-DB: AuthPayload, ProjectOverview, etc.)
  if (schema.types) {
    for (const t of Object.values(schema.types)) {
      out += `export interface ${t.name} {\n`
      for (const field of t.fields) {
        const ts = resolveFieldType(field, schema)
        out += field.nullable ? `  ${field.name}: ${ts} | null\n` : `  ${field.name}: ${ts}\n`
      }
      out += '}\n\n'
      out += genJSONDecode(t as unknown as LuxoModel, schema)

      // Binary decoder for type declarations (same logic as models)
      out += `export function decode${t.name}(dec: Decoder): ${t.name} {\n`
      out += `  const obj: Record<string, unknown> = {}\n`
      out += `  dec.skipArenaHeader()\n`
      out += `  while (dec.nextField()) {\n`
      out += `    switch (dec.fieldID) {\n`
      for (const field of t.fields) {
        out += `      case ${field.id}: obj['${field.name}'] = `
        out += genFieldRead(field, schema) + '; break\n'
      }
      out += `      default: break\n`
      out += `    }\n`
      out += `  }\n`
      out += `  return obj as unknown as ${t.name}\n`
      out += '}\n\n'

      // Columnar + paginated decoder for type declarations
      out += genColumnarDecode(t as unknown as LuxoModel, schema, true)
      out += genPaginatedDecode(t as unknown as LuxoModel, schema, true)
    }
  }

  // Model interfaces
  for (const model of Object.values(schema.models)) {
    out += `export interface ${model.name} {\n`
    for (const field of model.fields) {
      const ts = resolveFieldType(field, schema)
      out += field.nullable ? `  ${field.name}: ${ts} | null\n` : `  ${field.name}: ${ts}\n`
    }
    out += '}\n\n'
    out += genJSONDecode(model, schema)

    // Binary decoder function — reads from Luxo binary using field IDs
    out += `export function decode${model.name}(dec: Decoder): ${model.name} {\n`
    out += `  const obj: Record<string, unknown> = {}\n`
    out += `  dec.skipArenaHeader()\n`
    out += `  while (dec.nextField()) {\n`
    out += `    switch (dec.fieldID) {\n`
    for (const field of model.fields) {
      out += `      case ${field.id}: obj['${field.name}'] = `
      out += genFieldRead(field, schema) + '; break\n'
    }
    out += `      default: break\n`
    out += `    }\n`
    out += `  }\n`
    out += `  return obj as unknown as ${model.name}\n`
    out += '}\n\n'

    // Columnar decoder — decodes columnar binary to array
    out += genColumnarDecode(model, schema, true)

    // Paginated columnar decoder
    out += genPaginatedDecode(model, schema, true)
  }

  out += 'export type { Page }\n'
  return out
}

function genJSONDecode(model: LuxoModel, schema: LuxoSchema): string {
  let out = `export function decodeJSON${model.name}(data: Record<string, unknown>): ${model.name} {\n`
  out += `  return {\n`
  for (const field of model.fields) {
    const raw = `data['${field.name}']`
    const decoded = jsonValueDecode(field, schema, raw)
    const fallback = field.nullable ? 'null' : columnDefault(field, schema)
    out += `    ${field.name}: ${raw} == null ? ${fallback} : ${decoded},\n`
  }
  out += `  }\n`
  out += `}\n\n`
  return out
}

function jsonValueDecode(field: LuxoField, schema: LuxoSchema, value: string): string {
  const typeName = field.typeName || field.type
  const nested = isNestedField(field, schema)
  const element = nested ? `decodeJSON${typeName}(item as Record<string, unknown>)`
    : field.type === 'Int' || field.type === 'Float' || field.type === 'Duration' ? 'Number(item)'
    : field.type === 'Boolean' ? 'item as boolean'
    : field.type === 'Bytes' ? 'decodeBase64(item as string)'
    : field.type === 'JSON' ? 'item'
    : `item as ${resolveFieldType({ ...field, isList: false, list: false }, schema)}`
  if (field.isList || field.list) {
    return `(${value} as unknown[]).map(item => ${element})`
  }
  if (nested) return `decodeJSON${typeName}(${value} as Record<string, unknown>)`
  switch (field.type) {
    case 'Int': case 'Float': case 'Duration': return `Number(${value})`
    case 'Boolean': return `${value} as boolean`
    case 'Bytes': return `decodeBase64(${value} as string)`
    case 'JSON': return value
    default: return `${value} as ${resolveFieldType(field, schema)}`
  }
}

/** TypeScript array type for a column variable */
function isNestedField(field: LuxoField, schema: LuxoSchema): boolean {
  const typeName = field.typeName || field.type
  return Boolean(field.relation || schema.models[typeName] || schema.types?.[typeName])
}

function columnTSType(field: LuxoField, schema: LuxoSchema): string {
  if (isNestedField(field, schema) || field.isList || field.list || field.type === 'Bytes' || field.type === 'JSON') {
    return field.nullable && !field.isList && !field.list ? '(Uint8Array | null)[]' : 'Uint8Array[]'
  }
  const n = field.nullable
  switch (field.type) {
    case 'Int': case 'Duration': case 'Float':
      return n ? '(number | null)[]' : 'number[]'
    // DateTime is represented as an RFC3339 string in both JSON and binary modes.
    case 'String': case 'Enum': case 'UUID': case 'Decimal': case 'DateTime':
      return n ? '(string | null)[]' : 'string[]'
    case 'Boolean':
      return n ? '(boolean | null)[]' : 'boolean[]'
    default:
      return n ? '(string | null)[]' : 'string[]'
  }
}

/** Default value for missing column */
function columnDefault(field: LuxoField, schema: LuxoSchema): string {
  const typeName = field.typeName || field.type
  if (field.isList || field.list) return '[]'
  if (isNestedField(field, schema)) {
    return field.nullable ? 'null' : `undefined as unknown as ${typeName}`
  }
  if (field.nullable) return 'null'
  if (schema.enums?.[typeName]) return `'' as ${typeName}`
  switch (field.type) {
    case 'Int': case 'Duration': case 'Float': return '0'
    case 'Boolean': return 'false'
    case 'Bytes': return 'new Uint8Array(0)'
    case 'JSON': return 'null'
    // DateTime is a string (RFC3339) — default to empty string like other string columns.
    default: return "''"
  }
}

function genColumnRead(field: LuxoField, schema: LuxoSchema): string {
  if (isNestedField(field, schema) || field.isList || field.list || field.type === 'Bytes' || field.type === 'JSON') {
    return field.nullable && !field.isList && !field.list ? 'r.readColumnBytesPtr()' : 'r.readColumnBytes()'
  }
  const n = field.nullable
  switch (field.type) {
    case 'Int': case 'Duration':
      return n ? 'r.readColumnIntPtr()' : 'r.readColumnInt()'
    // DateTime columns are svarint(unix seconds), decoded to RFC3339 strings (matches JSON mode).
    case 'DateTime':
      return n ? 'r.readColumnDateTimePtr()' : 'r.readColumnDateTime()'
    case 'Float':
      return n ? 'r.readColumnFloatPtr()' : 'r.readColumnFloat()'
    case 'String': case 'Enum': case 'UUID': case 'Decimal':
      return n ? 'r.readColumnStringPtr()' : 'r.readColumnString()'
    case 'Boolean':
      return n ? 'r.readColumnBoolPtr()' : 'r.readColumnBool()'
    default:
      return n ? 'r.readColumnStringPtr()' : 'r.readColumnString()'
  }
}

function columnValue(field: LuxoField, schema: LuxoSchema): string {
  const column = `_${field.name}`
  const typeName = field.typeName || field.type
  if (isNestedField(field, schema)) {
    if (field.isList || field.list) {
      return `${column} ? decodeColumnar${typeName}(${column}[i]) : []`
    }
		const decoded = `decode${typeName}(new Decoder(${column}[i]!))`
		if (field.nullable) {
			return `${column} && ${column}[i] ? ${decoded} : null`
    }
    return `${column} ? ${decoded} : undefined as unknown as ${typeName}`
  }
  if (field.isList || field.list) {
    const ts = resolveFieldType({ ...field, isList: false, list: false }, schema)
    return `${column} ? decodeScalarArray(${column}[i], '${field.type}') as ${ts}[] : []`
  }
  if (field.type === 'JSON') {
    const decoded = `decodeJSONValue(${column}![i]!)`
    return field.nullable
      ? `${column} && ${column}[i] ? ${decoded} : null`
      : `${column} ? ${decoded} : null`
  }
  return `${column} ? ${column}[i] : ${columnDefault(field, schema)}`
}

function columnarFields(model: LuxoModel, includeNested: boolean): LuxoField[] {
  return includeNested ? model.fields : model.fields.filter(f => !f.relation)
}

function genColumnarDecode(model: LuxoModel, schema: LuxoSchema, includeNested: boolean): string {
  const fields = columnarFields(model, includeNested)
  let out = `export function decodeColumnar${model.name}(data: Uint8Array): ${model.name}[] {\n`
  out += `  const r = new ColumnarDecoder(data)\n`
  // Typed column variables — zero Record overhead, zero type assertion
  for (const f of fields) {
    out += `  let _${f.name}: ${columnTSType(f, schema)} | undefined\n`
  }
  out += `  while (r.nextColumn()) {\n`
  out += `    switch (r.fieldID) {\n`
  for (const f of fields) {
    out += `      case ${f.id}: _${f.name} = ${genColumnRead(f, schema)}; break\n`
  }
  out += `      default: break\n`
  out += `    }\n`
  out += `  }\n`
  out += `  const items: ${model.name}[] = new Array(r.count)\n`
  out += `  for (let i = 0; i < r.count; i++) {\n`
  out += `    items[i] = {\n`
  for (const f of fields) {
    out += `      ${f.name}: ${columnValue(f, schema)},\n`
  }
  out += `    } as unknown as ${model.name}\n`
  out += `  }\n`
  out += `  return items\n`
  out += '}\n\n'
  return out
}

function genPaginatedDecode(model: LuxoModel, schema: LuxoSchema, includeNested: boolean): string {
  const fields = columnarFields(model, includeNested)
  let out = `export function decodePaginated${model.name}(data: Uint8Array): Page<${model.name}> {\n`
  out += `  const r = new ColumnarDecoder(data)\n`
  for (const f of fields) {
    out += `  let _${f.name}: ${columnTSType(f, schema)} | undefined\n`
  }
  out += `  while (r.nextColumn()) {\n`
  out += `    switch (r.fieldID) {\n`
  for (const f of fields) {
    out += `      case ${f.id}: _${f.name} = ${genColumnRead(f, schema)}; break\n`
  }
  out += `      default: break\n`
  out += `    }\n`
  out += `  }\n`
  out += `  const items: ${model.name}[] = new Array(r.count)\n`
  out += `  for (let i = 0; i < r.count; i++) {\n`
  out += `    items[i] = {\n`
  for (const f of fields) {
    out += `      ${f.name}: ${columnValue(f, schema)},\n`
  }
  out += `    } as unknown as ${model.name}\n`
  out += `  }\n`
  out += `  const total = r.readSvarint()\n`
  out += `  const page = r.readSvarint()\n`
  out += `  const pageSize = r.readSvarint()\n`
  out += `  return { items, total, page, pageSize }\n`
  out += '}\n\n'
  return out
}

function genFieldRead(field: { type: string; typeName?: string; nullable?: boolean; isList?: boolean; relation?: boolean }, schema: LuxoSchema): string {
  const n = field.nullable

  // Check for nested model/type reference first (relation fields or typeName pointing to a model/type)
  const tn = field.typeName || field.type
  if (field.relation || (tn && (schema.models[tn] || schema.types?.[tn]))) {
    if (field.isList) {
      return `dec.readArray(() => decode${tn}(dec))`
    }
    return n ? `dec.readNullable(() => decode${tn}(dec))` : `decode${tn}(dec)`
  }

  if (field.isList) {
    switch (field.type) {
      case 'Int': case 'Duration': return 'dec.readIntArray()'
      case 'DateTime': return 'dec.readIntArray().map(unixSecondsToISO)'
      case 'Float': return 'dec.readFloatArray()'
      case 'String': case 'Decimal': case 'Enum': return 'dec.readStringArray()'
      case 'Boolean': return 'dec.readBoolArray()'
      case 'UUID': return 'dec.readUUIDArray()'
      case 'Bytes': return 'dec.readBytesArray()'
      case 'JSON': return 'dec.readBytesArray().map(decodeJSONValue)'
      default: return '[]'
    }
  }

  switch (field.type) {
    case 'Int': case 'Duration': return n ? 'dec.readIntPtr()' : 'dec.readInt()'
    case 'Float': return n ? 'dec.readFloatPtr()' : 'dec.readFloat()'
    // DateTime is svarint(unix seconds) on the wire, decoded to an RFC3339 string (matches JSON mode).
    case 'DateTime': return n ? 'dec.readDateTimePtr()' : 'dec.readDateTime()'
    // UUID is a fixed 16-byte wire value (not a length-prefixed string) — use the
    // dedicated codec method so generated code matches the protocol.
    case 'UUID': return n ? 'dec.readUUIDPtr()' : 'dec.readUUID()'
    case 'String': case 'Decimal': case 'Enum':
      return n ? 'dec.readStringPtr()' : 'dec.readString()'
    case 'Boolean': return n ? 'dec.readBoolPtr()' : 'dec.readBool()'
    case 'Bytes': return n ? 'dec.readNullable(() => dec.readBytes())' : 'dec.readBytes()'
    case 'JSON': return n ? 'dec.readNullable(() => decodeJSONValue(dec.readBytes()))' : 'decodeJSONValue(dec.readBytes())'
    default: {
      const fallbackTn = field.typeName || field.type
      if (schema.models[fallbackTn] || schema.types?.[fallbackTn]) {
        if (field.isList) {
          return `dec.readArray(() => decode${fallbackTn}(dec))`
        }
        return n ? `dec.readNullable(() => decode${tn}(dec))` : `decode${tn}(dec)`
      }
      return 'null' // unknown type — should not happen with valid schema
    }
  }
}

// --- schema.ts ---

function genSchema(schema: LuxoSchema): string {
  let out = '// Auto-generated by @luxo/vite-plugin. DO NOT EDIT.\n\n'
  out += "import type { APISchema } from '@luxojs/client'\n\n"

  out += 'const LUXO_SELECTION_TYPES = {\n'
  const selectionTypes = { ...(schema.types ?? {}), ...schema.models }
  for (const type of Object.values(selectionTypes)) {
    const fields = type.fields.map(field => {
      const typeName = field.typeName || field.type
      const nested = isNestedField(field, schema) ? `, typeName: '${typeName}'` : ''
      return `'${field.name}': { fieldID: ${field.id}${nested} }`
    }).join(', ')
    out += `  '${type.name}': { ${fields} },\n`
  }
  out += '}\n\n'

  out += '/** API schema map — used by binary transport for encoding requests. */\n'
  out += 'export const LUXO_SCHEMA: Record<string, APISchema> = {\n'
  for (const api of Object.values(schema.apis)) {
    if (api.name.startsWith('svc:')) continue
    out += `  '${api.name}': { id: ${api.id}`
    const returnFields = api.returnType
      ? schema.models[api.returnType]?.fields ?? schema.types?.[api.returnType]?.fields
      : undefined
    if (returnFields && returnFields.length > 0) {
      out += `, fields: LUXO_SELECTION_TYPES['${api.returnType}'], types: LUXO_SELECTION_TYPES`
    }
    if (api.params && api.params.length > 0) {
      out += ', params: [\n'
      for (const p of api.params) {
		out += `    { fieldID: ${p.id}, name: '${p.name}', type: '${p.type}'${p.isList ? ', isList: true' : ''}${p.nullable ? ', nullable: true' : ''} },\n`
      }
      out += '  ]'
    }
    out += ' },\n'
  }
  out += '}\n'
  return out
}

// --- client.ts ---

function genClient(schema: LuxoSchema): string {
  let out = '// Auto-generated by @luxo/vite-plugin. DO NOT EDIT.\n\n'
  out += "import type { Transport, TransportOptions, CallOptions, Page, Filter, Sorter } from '@luxojs/client'\n"
  const runtimeImports = ['FetchTransport', 'WsTransport']
  const decodeExpressions = Object.values(schema.apis).map(genDecode).join('\n')
  for (const helper of ['Decoder', 'decodeBase64', 'decodeJSONValue', 'unixSecondsToISO']) {
    if (decodeExpressions.includes(`${helper}(`) || decodeExpressions.includes(`new ${helper}(`)) runtimeImports.push(helper)
  }
  out += `import { ${runtimeImports.join(', ')} } from '@luxojs/client'\n`
  out += "import { LUXO_SCHEMA } from './schema'\n"

  // Collect model type imports + decoder imports
  const typeImports = new Set<string>()
  const decoderImports = new Set<string>()
  for (const api of Object.values(schema.apis)) {
    if (api.returnType && !isScalar(api.returnType)) {
      typeImports.add(api.returnType)
      if (api.paginated) {
        decoderImports.add(`decodePaginated${api.returnType}`)
      } else if (api.returnList) {
        decoderImports.add(`decodeColumnar${api.returnType}`)
      } else {
        decoderImports.add(`decode${api.returnType}`)
      }
      decoderImports.add(`decodeJSON${api.returnType}`)
    }
		for (const param of api.params ?? []) {
			const typeName = param.typeName || param.type
			if (schema.enums?.[typeName] || schema.models[typeName] || schema.types?.[typeName]) {
				typeImports.add(typeName)
			}
		}
  }
  if (typeImports.size > 0) {
    out += `import type { ${Array.from(typeImports).join(', ')} } from './types'\n`
	}
	if (decoderImports.size > 0) {
    out += `import { ${Array.from(decoderImports).join(', ')} } from './types'\n`
  }

  out += '\nexport class LuxoClient {\n'
  out += '  private transport: Transport\n\n'

  // Constructor: accepts Transport directly
  out += '  constructor(transport: Transport) {\n'
  out += '    this.transport = transport\n'
  out += '    transport.setSchema(LUXO_SCHEMA)\n'
  out += '  }\n\n'

  // Factory: auto-detect transport from URL scheme
  out += '  /** Create client from URL — auto-detects HTTP vs WebSocket transport. */\n'
  out += '  static create(endpoint: string, options?: TransportOptions): LuxoClient {\n'
  out += '    const transport = endpoint.startsWith(\'ws\') ? new WsTransport(endpoint, options) : new FetchTransport(endpoint, options)\n'
  out += '    return new LuxoClient(transport)\n'
  out += '  }\n\n'

  out += '  /** Switch transport mode (json for debug, binary for production). */\n'
  out += '  setMode(mode: \'json\' | \'binary\'): void { this.transport.setMode(mode) }\n\n'
  out += '  /** Update auth token. */\n'
  out += '  setToken(token: string | null): void { this.transport.setToken(token) }\n\n'
  out += '  /** Close transport (WebSocket). */\n'
  out += '  close(): void { this.transport.close?.() }\n\n'
  out += '  static readonly schema = LUXO_SCHEMA\n\n'

  for (const api of Object.values(schema.apis)) {
    if (api.name.startsWith('svc:')) continue
    out += genMethod(api, schema)
  }

  out += '}\n'
  return out
}

function genDecode(api: LuxoAPI): string {
  const t = api.returnType
  if (!t) return 'd instanceof Uint8Array ? new Decoder(d).readInt() : d as number'

  if (isScalar(t)) {
    const ts = luxoTypeToTS(t)
    const br = t === 'Float' ? 'new Decoder(d).readFloat()'
      : t === 'Boolean' ? 'new Decoder(d).readBool()'
      : (t === 'Int' || t === 'Duration') ? 'new Decoder(d).readInt()'
      : t === 'DateTime' ? 'new Decoder(d).readDateTime()'
      : t === 'UUID' ? 'new Decoder(d).readUUID()'
      : t === 'Bytes' ? 'new Decoder(d).readBytes()'
      : t === 'JSON' ? 'decodeJSONValue(new Decoder(d).readBytes())'
      : 'new Decoder(d).readString()'
    if (api.returnList) {
      const listBR = t === 'Float' ? 'new Decoder(d).readFloatArray()'
        : t === 'Boolean' ? 'new Decoder(d).readBoolArray()'
        : (t === 'Int' || t === 'Duration') ? 'new Decoder(d).readIntArray()'
        : t === 'DateTime' ? 'new Decoder(d).readIntArray().map(unixSecondsToISO)'
        : t === 'UUID' ? 'new Decoder(d).readUUIDArray()'
        : t === 'Bytes' ? 'new Decoder(d).readBytesArray()'
        : t === 'JSON' ? 'new Decoder(d).readBytesArray().map(decodeJSONValue)'
        : 'new Decoder(d).readStringArray()'
      const listJSON = t === 'Bytes' ? '(d as string[]).map(decodeBase64)' : `d as ${ts}[]`
      return `d instanceof Uint8Array ? ${listBR} : ${listJSON}`
    }
    const json = t === 'Bytes' ? 'decodeBase64(d as string)' : `d as ${ts}`
    return `d instanceof Uint8Array ? ${br} : ${json}`
  }

  if (api.paginated) {
    const p = `(d as Record<string, unknown>)`
    return `d instanceof Uint8Array ? decodePaginated${t}(d) : { items: (${p}['items'] as unknown[]).map(v => decodeJSON${t}(v as Record<string, unknown>)), total: Number(${p}['total']), page: Number(${p}['page']), pageSize: Number(${p}['pageSize']) }`
  }
  if (api.returnList) {
    return `d instanceof Uint8Array ? decodeColumnar${t}(d) : (d as unknown[]).map(v => decodeJSON${t}(v as Record<string, unknown>))`
  }

  const binDec = `decode${t}(new Decoder(d))`
  return `d instanceof Uint8Array ? ${binDec} : decodeJSON${t}(d as Record<string, unknown>)`
}

function resolveParamType(p: { type: string; typeName?: string; name: string; isList?: boolean }, schema: LuxoSchema): string {
  let type: string
  const typeName = p.typeName || p.type
  if (schema.enums?.[typeName]) type = typeName
  else if (schema.models[typeName]) type = typeName
  else if (schema.types?.[typeName]) type = typeName
  else type = luxoTypeToTS(p.type)
  return p.isList ? `${type}[]` : type
}

function genMethod(api: LuxoAPI, schema: LuxoSchema): string {
  const retTS = getReturnType(api)
  const decode = genDecode(api)
  if (api.stream) return genStreamMethod(api, schema, retTS, decode)
  const structuredReturn = Boolean(api.returnType && !isScalar(api.returnType))
  const paginationNames = new Set(['page', 'pageSize'])
  const call = (params: string) =>
    `    const d = await this.transport.call('${api.name}', ${params || 'undefined'}, options)\n` +
    `    return ${decode}\n`

  // If API has explicit params, always use them for the signature (no guessing by name prefix)
  if (api.params && api.params.length > 0) {
    const paramFields = api.params.map(p => {
      if ((api.paginated && paginationNames.has(p.name)) || p.hasDefault) {
        return `${p.name}?: ${resolveParamType(p, schema)}${p.nullable ? ' | null' : ''}`
      }
      return `${p.name}: ${resolveParamType(p, schema)}${p.nullable ? ' | null' : ''}`
    })
    if (structuredReturn) paramFields.push('$select?: string')
    if (api.paginated) {
      if (!api.params.some(p => p.name === 'page')) paramFields.push('page?: number')
      if (!api.params.some(p => p.name === 'pageSize')) paramFields.push('pageSize?: number')
      paramFields.push('$filters?: Filter[]', '$sorters?: Sorter[]')
    }
    const hasRequiredParam = api.params.some(p => !p.hasDefault && !(api.paginated && paginationNames.has(p.name)))
    const optional = hasRequiredParam ? '' : '?'
    return `  async ${api.name}(params${optional}: { ${paramFields.join('; ')} }, options?: CallOptions): Promise<${retTS}> {\n` +
           call('params') + `  }\n\n`
  }

  if (api.paginated) {
    const selection = structuredReturn ? '$select?: string; ' : ''
    return `  async ${api.name}(params?: { page?: number; pageSize?: number; ${selection}$filters?: Filter[]; $sorters?: Sorter[] }, options?: CallOptions): Promise<${retTS}> {\n` +
           call('params') + `  }\n\n`
  }

  if (structuredReturn) {
    return `  async ${api.name}(params?: { $select?: string }, options?: CallOptions): Promise<${retTS}> {\n` +
           call('params') + `  }\n\n`
  }

  return `  async ${api.name}(options?: CallOptions): Promise<${retTS}> {\n` +
         call('') + `  }\n\n`
}

function genStreamMethod(api: LuxoAPI, schema: LuxoSchema, retTS: string, decode: string): string {
  const methodName = `subscribe${api.name.charAt(0).toUpperCase()}${api.name.slice(1)}`
  const paramFields = api.params?.map(param => {
    const optional = param.hasDefault ? '?' : ''
    const nullable = param.nullable ? ' | null' : ''
    return `${param.name}${optional}: ${resolveParamType(param, schema)}${nullable}`
  }) ?? []
  if (api.returnType && !isScalar(api.returnType)) paramFields.push('$select?: string')
  const fields = paramFields.join('; ')
  const hasRequiredParam = api.params?.some(param => !param.hasDefault) ?? false
  const params = fields ? `params${hasRequiredParam ? '' : '?'}: { ${fields} }, ` : ''
  const values = fields ? 'params ?? {}' : '{}'
  return `  ${methodName}(${params}onData: (data: ${retTS}) => void): Promise<() => void> {\n` +
    `    return this.transport.subscribe('${api.name}', ${values}, d => onData(${decode}))\n` +
    `  }\n\n`
}

function getReturnType(api: LuxoAPI): string {
  if (!api.returnType) return 'number'
  const ts = luxoTypeToTS(api.returnType)
  if (api.paginated) return `Page<${ts}>`
  if (api.returnList) return `${ts}[]`
  return ts
}

function isScalar(type: string): boolean {
  return ['Int', 'Float', 'String', 'Boolean', 'DateTime', 'Duration', 'UUID', 'Bytes', 'Decimal', 'JSON', 'Enum'].includes(type)
}
