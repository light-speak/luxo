package com.luxo.client

internal object KotlinQueryCodegen {
    private val identifier = Regex("[A-Za-z_][A-Za-z0-9_]*")
    private fun checkName(name: String) = require(identifier.matches(name)) { "invalid query identifier: $name" }

    private fun type(name: String, isEnum: Boolean): String = when {
        isEnum -> name
        name == "Int" -> "Long"
        name == "Float" -> "Double"
        name == "Boolean" -> "Boolean"
        name in listOf("String", "UUID", "DateTime", "Decimal") -> "String"
        else -> error("unsupported query type: $name")
    }

    private fun operators(name: String, isEnum: Boolean): List<String> = when {
        isEnum || name in listOf("Boolean", "UUID") -> listOf("eq", "ne")
        name == "String" -> listOf("eq", "ne", "contains", "startswith", "endswith", "match")
        else -> listOf("eq", "ne", "gt", "gte", "lt", "lte")
    }

    fun generate(schema: LuxoSchema, pkg: String): String = buildString {
        appendLine("// Code generated by luxo. DO NOT EDIT.")
        appendLine("package $pkg\nimport com.luxo.client.LuxoFilter\nimport com.luxo.client.LuxoSorter")
        for (api in schema.apis.values) {
            val query = api.query ?: continue
            if (api.isInternal) continue
            checkName(api.name)
            val generatedName = "LuxoQuery_${api.name}"
            require(generatedName !in schema.models && generatedName !in schema.types && generatedName !in schema.enums) {
                "query builder conflicts with declared type: $generatedName"
            }
            require(api.paginated && !api.stream) { "query controls require a paginated unary API: ${api.name}" }
            appendLine("object LuxoQuery_${api.name} {")
            val fields = mutableSetOf<String>()
            for (field in query.filters) {
                checkName(field.field)
                checkName(field.type)
                require(fields.add(field.field)) { "duplicate query field: ${field.field}" }
                val isEnum = schema.enums.containsKey(field.type)
                val type = type(field.type, isEnum)
                val value = if (isEnum) "value.rawValue" else "value"
                val allowed = operators(field.type, isEnum)
                require(field.operators.isNotEmpty()) { "empty query operators: ${field.field}" }
                val seen = mutableSetOf<String>()
                for (op in field.operators) {
                    require(op in allowed && seen.add(op)) { "invalid query operator: $op" }
                    appendLine("    fun ${field.field}_$op(value: $type): LuxoFilter = LuxoFilter(\"${field.field}\", \"$op\", $value)")
                }
            }
            fields.clear()
            for (field in query.sorters) {
                checkName(field)
                require(fields.add(field)) { "duplicate sorter field: $field" }
                for (order in listOf("asc", "desc")) {
                    appendLine("    fun ${field}_$order(): LuxoSorter = LuxoSorter(\"$field\", \"$order\")")
                }
            }
            appendLine("}")
        }
    }
}
