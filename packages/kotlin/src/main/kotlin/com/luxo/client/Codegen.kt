package com.luxo.client

import kotlinx.serialization.json.*
import java.io.File
import java.net.HttpURLConnection
import java.net.URI

/**
 * Generate typed Kotlin client from Luxo schema introspection.
 *
 * Usage:
 *   LuxoCodegen.generate(
 *     endpoint = "http://localhost:4000/luvia",
 *     key = "YOUR_KEY",
 *     outDir = "src/main/kotlin/com/example/luxo",
 *     packageName = "com.example.luxo",
 *   )
 */
object LuxoCodegen {

    fun generate(
        endpoint: String,
        key: String,
        outDir: String,
        packageName: String = "com.luxo.generated",
        schemaFile: String? = null,
    ) {
        val connection = introspectionConnection(endpoint, key)
        val body = try {
            val status = connection.responseCode
            if (status != HttpURLConnection.HTTP_OK) {
                throw RuntimeException("HTTP $status")
            }
            connection.inputStream.bufferedReader().use { it.readText() }
        } catch (e: Exception) {
            throw RuntimeException("luxo introspection failed: ${e.message}", e)
        } finally {
            connection.disconnect()
        }
        val schema = try {
            Json.decodeFromString<LuxoSchema>(body)
        } catch (e: Exception) {
            throw RuntimeException("luxo introspection returned invalid JSON: ${e.message}", e)
        }
        if (schemaFile != null) {
            val snapshot = File(schemaFile)
            snapshot.parentFile?.mkdirs()
            snapshot.writeText(body)
        }

        File(outDir).mkdirs()
        File("$outDir/Types.kt").writeText(genTypes(schema, packageName))
        File("$outDir/Schema.kt").writeText(genSchemaMap(schema, packageName))
        File("$outDir/LuxoClient.kt").writeText(genClient(schema, packageName))
        File("$outDir/SelectHints.kt").writeText(genSelectHints(packageName, emptyMap()))
        println("[luxo] Generated types -> $outDir/")
    }

    internal fun genSelectHints(packageName: String, hints: Map<String, String>): String = buildString {
        appendLine("// Auto-generated by luxo. DO NOT EDIT.\n")
        appendLine("package $packageName\n")
        appendLine("/** Compile-time \$select hints per API. */")
        appendLine("object SelectHints {")
        if (hints.isEmpty()) {
            appendLine("    val hints: Map<String, String> = emptyMap()")
        } else {
            appendLine("    val hints: Map<String, String> = mapOf(")
            for ((api, select) in hints.toSortedMap()) appendLine("        \"$api\" to \"$select\",")
            appendLine("    )")
        }
        appendLine("}")
    }

    internal fun introspectionConnection(endpoint: String, key: String): HttpURLConnection {
        return (URI("$endpoint?\$schema").toURL().openConnection() as HttpURLConnection).apply {
            requestMethod = "GET"
            setRequestProperty("X-Introspection-Key", key)
        }
    }

    private fun luxoTypeToKt(type: String): String = when (type) {
        "Int", "Duration" -> "Long"
        "Float" -> "Double"
        "String", "DateTime", "UUID", "Decimal", "Enum" -> "String"
        "Boolean" -> "Boolean"
        "Bytes" -> "ByteArray"
        "JSON" -> "JsonElement"
        else -> type
    }

    private fun resolveFieldType(f: LuxoField, schema: LuxoSchema): String {
        val tn = f.typeName ?: f.type
        if (schema.enums.containsKey(tn)) return if (f.isList) "List<$tn>" else tn
        if (schema.models.containsKey(tn)) return if (f.isList) "List<$tn>" else tn
        if (schema.types.containsKey(tn)) return if (f.isList) "List<$tn>" else tn
        val base = luxoTypeToKt(f.type)
        return if (f.isList) "List<$base>" else base
    }

    /** Kotlin type for an API param, wrapping list params in List<>. */
    private fun paramKtType(p: LuxoParam, schema: LuxoSchema): String {
        val typeName = p.typeName ?: p.type
        val base = if (
            schema.enums.containsKey(typeName) || schema.models.containsKey(typeName) || schema.types.containsKey(typeName)
        ) typeName else luxoTypeToKt(p.type)
        return if (p.isList) "List<$base>" else base
    }

    private fun paramTransportValue(
        p: LuxoParam,
        schema: LuxoSchema,
        expression: String = p.name,
        nullable: Boolean = p.nullable,
    ): String {
        val typeName = p.typeName ?: p.type
        val structured = schema.models.containsKey(typeName) || schema.types.containsKey(typeName)
        if (!structured) return expression
        return when {
            p.isList && nullable -> "$expression?.map { Json.encodeToJsonElement(it) }"
            p.isList -> "$expression.map { Json.encodeToJsonElement(it) }"
            nullable -> "$expression?.let { Json.encodeToJsonElement(it) }"
            else -> "Json.encodeToJsonElement($expression)"
        }
    }

    private fun isScalar(type: String): Boolean =
        type in setOf(
            "Int", "Float", "String", "Boolean", "DateTime", "Duration",
            "UUID", "Bytes", "Decimal", "JSON",
        )

    /** Element reader expression for a scalar type (used inside readArray). */
    private fun scalarElementRead(type: String, decoder: String = "dec"): String = when (type) {
        "Int", "Duration" -> "$decoder.readInt()"
        "Float" -> "$decoder.readFloat()"
        "Boolean" -> "$decoder.readBool()"
        "UUID" -> "$decoder.readUuid()"
        "DateTime" -> "$decoder.readDateTime()" // svarint(unix seconds) -> ISO string
        "Bytes" -> "$decoder.readBytes()"
        "JSON" -> "Json.parseToJsonElement($decoder.readBytes().toString(Charsets.UTF_8))"
        else -> "$decoder.readString()" // String, Decimal, Enum
    }

    private fun binaryRead(f: LuxoField): String {
        val n = f.nullable
        // Scalar arrays: [count][items...] — decode element-by-element.
        if (f.isList && isScalar(f.type)) {
            return "dec.readArray { ${scalarElementRead(f.type)} }"
        }
        return when (f.type) {
            "Int", "Duration" -> if (n) "dec.readIntPtr()" else "dec.readInt()"
            "Float" -> if (n) "dec.readFloatPtr()" else "dec.readFloat()"
            "Boolean" -> if (n) "dec.readBoolPtr()" else "dec.readBool()"
            "UUID" -> if (n) "dec.readUuidPtr()" else "dec.readUuid()"
            "Bytes" -> if (n) "dec.readNullable { dec.readBytes() }" else "dec.readBytes()"
            "JSON" -> {
                val read = "Json.parseToJsonElement(dec.readBytes().toString(Charsets.UTF_8))"
                if (n) "dec.readNullable { $read }" else read
            }
            // DateTime: svarint(unix seconds) on the wire -> ISO string (matches JSON mode).
            "DateTime" -> if (n) "dec.readDateTimePtr()" else "dec.readDateTime()"
            "String", "Decimal", "Enum" -> if (n) "dec.readStringPtr()" else "dec.readString()"
            else -> {
                // Nested model — decode recursively
                val tn = f.typeName ?: f.type
                if (f.isList) "dec.readArray { decode$tn(dec) }"
                else if (n) "dec.readNullable { decode$tn(dec) }"
                else "decode$tn(dec)"
            }
        }
    }

    internal fun genTypes(schema: LuxoSchema, pkg: String): String = buildString {
        appendLine("// Auto-generated by luxo. DO NOT EDIT.\n")
        appendLine("package $pkg\n")
        appendLine("import com.luxo.client.ColumnarDecoder")
        appendLine("import com.luxo.client.LuxoDecoder")
        appendLine("import com.luxo.client.Page")
        appendLine("import kotlinx.serialization.Serializable")
        appendLine("import kotlinx.serialization.json.*\n")

        // Enums
        for (e in schema.enums.values) {
            appendLine("/** ${e.name} enum values */")
            appendLine("typealias ${e.name} = String")
            appendLine("object ${e.name}Values {")
            for (v in e.values) {
                appendLine("    const val $v: ${e.name} = \"$v\"")
            }
            appendLine("    val all = listOf(${e.values.joinToString(", ") { "\"$it\"" }})")
            appendLine("}\n")
        }

        // Type declarations (non-DB)
        for (t in schema.types.values) {
            appendLine("@Serializable\ndata class ${t.name}(")
            for ((i, f) in t.fields.withIndex()) {
                val kt = resolveFieldType(f, schema)
                val nullable = if (f.nullable) "? = null" else ""
                val comma = if (i < t.fields.size - 1) "," else ""
                appendLine("    val ${f.name}: $kt$nullable$comma")
            }
            appendLine(")\n")
            append(generateKotlinDecoders(t.name, t.fields, schema))
        }

        // Models
        for (m in schema.models.values) {
            appendLine("@Serializable\ndata class ${m.name}(")
            for ((i, f) in m.fields.withIndex()) {
                val kt = resolveFieldType(f, schema)
                val nullable = if (f.nullable) "? = null" else ""
                val comma = if (i < m.fields.size - 1) "," else ""
                appendLine("    val ${f.name}: $kt$nullable$comma")
            }
            appendLine(")\n")
            append(generateKotlinDecoders(m.name, m.fields, schema))
        }
    }

    private fun generateKotlinDecoders(name: String, fields: List<LuxoField>, schema: LuxoSchema): String = buildString {
        appendLine("fun decode$name(dec: LuxoDecoder): $name {")
        for (f in fields) {
            appendLine("    var _${f.name}: ${resolveFieldType(f, schema)}? = null")
        }
        appendLine("    dec.skipArenaHeader()")
        appendLine("    while (dec.nextField()) {")
        appendLine("        when (dec.fieldID) {")
        for (f in fields) appendLine("            ${f.id} -> _${f.name} = ${binaryRead(f)}")
        appendLine("        }")
        appendLine("    }")
        appendLine("    return $name(")
        for (f in fields) {
            val value = if (f.nullable) "_${f.name}" else "_${f.name} ?: ${kotlinFieldDefault(f)}"
            appendLine("        ${f.name} = $value,")
        }
        appendLine("    )")
        appendLine("}\n")
        append(generateKotlinJSONDecoder(name, fields, schema))
        append(generateKotlinColumnarDecoder(name, fields, schema, false))
        append(generateKotlinColumnarDecoder(name, fields, schema, true))
    }

    private fun generateKotlinJSONDecoder(name: String, fields: List<LuxoField>, schema: LuxoSchema): String = buildString {
        appendLine("fun decodeJSON$name(data: JsonObject): $name = $name(")
        for (field in fields) {
            val raw = "data[\"${field.name}\"]"
            val decoded = kotlinJSONValue(field, schema, "value")
            val value = if (field.nullable) {
                "$raw?.takeUnless { it is JsonNull }?.let { value -> $decoded }"
            } else {
                "$raw?.let { value -> $decoded } ?: ${kotlinFieldDefault(field)}"
            }
            appendLine("    ${field.name} = $value,")
        }
        appendLine(")\n")
    }

    private fun kotlinJSONValue(field: LuxoField, schema: LuxoSchema, value: String): String {
        val typeName = field.typeName ?: field.type
        val element = when {
            isNested(field, schema) -> "decodeJSON$typeName(item.jsonObject)"
            field.type in setOf("Int", "Duration") -> "item.jsonPrimitive.long"
            field.type == "Float" -> "item.jsonPrimitive.double"
            field.type == "Boolean" -> "item.jsonPrimitive.boolean"
            field.type == "Bytes" -> "java.util.Base64.getDecoder().decode(item.jsonPrimitive.content)"
            field.type == "JSON" -> "item"
            else -> "item.jsonPrimitive.content"
        }
        if (field.isList) return "$value.jsonArray.map { item -> $element }"
        return when {
            isNested(field, schema) -> "decodeJSON$typeName($value.jsonObject)"
            field.type in setOf("Int", "Duration") -> "$value.jsonPrimitive.long"
            field.type == "Float" -> "$value.jsonPrimitive.double"
            field.type == "Boolean" -> "$value.jsonPrimitive.boolean"
            field.type == "Bytes" -> "java.util.Base64.getDecoder().decode($value.jsonPrimitive.content)"
            field.type == "JSON" -> value
            else -> "$value.jsonPrimitive.content"
        }
    }

    private fun generateKotlinColumnarDecoder(
        name: String,
        fields: List<LuxoField>,
        schema: LuxoSchema,
        paginated: Boolean,
    ): String = buildString {
        val function = if (paginated) "decodePaginated$name" else "decodeColumnar$name"
        val result = if (paginated) "Page<$name>" else "List<$name>"
        appendLine("fun $function(data: ByteArray): $result {")
        appendLine("    val dec = ColumnarDecoder(data)")
        for (f in fields) appendLine("    var _${f.name}: ${kotlinColumnType(f, schema)}? = null")
        appendLine("    while (dec.nextColumn()) {")
        appendLine("        when (dec.fieldID) {")
        for (f in fields) appendLine("            ${f.id} -> _${f.name} = ${kotlinColumnRead(f, schema)}")
        appendLine("        }")
        appendLine("    }")
        appendLine("    val items = List(dec.count) { i -> $name(")
        for (f in fields) appendLine("        ${f.name} = ${kotlinColumnValue(f, schema)},")
        appendLine("    ) }")
        if (paginated) {
            appendLine("    return Page(items, dec.readSvarint().toInt(), dec.readSvarint().toInt(), dec.readSvarint().toInt())")
        } else {
            appendLine("    return items")
        }
        appendLine("}\n")
    }

    private fun isNested(f: LuxoField, schema: LuxoSchema): Boolean {
        val name = f.typeName ?: f.type
        return f.relation || schema.models.containsKey(name) || schema.types.containsKey(name)
    }

    private fun kotlinColumnType(f: LuxoField, schema: LuxoSchema): String {
        if (isNested(f, schema) || f.isList || f.type == "Bytes" || f.type == "JSON") {
            return if (f.nullable && !f.isList) "List<ByteArray?>" else "List<ByteArray>"
        }
        val base = resolveFieldType(f, schema)
        return if (f.nullable) "List<$base?>" else "List<$base>"
    }

    private fun kotlinColumnRead(f: LuxoField, schema: LuxoSchema): String {
        if (isNested(f, schema) || f.isList || f.type == "Bytes" || f.type == "JSON") {
            return if (f.nullable && !f.isList) "dec.readColumnBytesPtr()" else "dec.readColumnBytes()"
        }
        return when (f.type) {
            "Int", "Duration" -> if (f.nullable) "dec.readColumnIntPtr()" else "dec.readColumnInt()"
            "Float" -> if (f.nullable) "dec.readColumnFloatPtr()" else "dec.readColumnFloat()"
            "Boolean" -> if (f.nullable) "dec.readColumnBoolPtr()" else "dec.readColumnBool()"
            "DateTime" -> if (f.nullable) "dec.readColumnDateTimePtr()" else "dec.readColumnDateTime()"
            "UUID" -> if (f.nullable) "dec.readColumnUuidPtr()" else "dec.readColumnUuid()"
            else -> if (f.nullable) "dec.readColumnStringPtr()" else "dec.readColumnString()"
        }
    }

    private fun kotlinColumnValue(f: LuxoField, schema: LuxoSchema): String {
        val column = "_${f.name}"
        val typeName = f.typeName ?: f.type
        if (isNested(f, schema)) {
            if (f.isList) return "$column?.get(i)?.let(::decodeColumnar$typeName) ?: emptyList()"
            val decoded = "decode$typeName(LuxoDecoder($column!![i]!!))"
            return if (f.nullable) "$column?.get(i)?.let { decode$typeName(LuxoDecoder(it)) }"
            else "if ($column == null) ${kotlinFieldDefault(f)} else $decoded"
        }
        if (f.isList) {
            val element = scalarElementRead(f.type, "cell")
            return "$column?.get(i)?.let { LuxoDecoder(it).let { cell -> cell.readArray { $element } } } ?: emptyList()"
        }
        if (f.type == "JSON") {
            val decoded = "Json.parseToJsonElement($column!![i]!!.toString(Charsets.UTF_8))"
            return if (f.nullable) "$column?.get(i)?.let { Json.parseToJsonElement(it.toString(Charsets.UTF_8)) }"
            else "if ($column == null) JsonNull else $decoded"
        }
        return "$column?.get(i) ?: ${if (f.nullable) "null" else kotlinFieldDefault(f)}"
    }

    private fun kotlinFieldDefault(f: LuxoField): String {
        if (f.isList) return "emptyList()"
        return when (f.type) {
            "Int", "Duration" -> "0L"
            "Float" -> "0.0"
            "Boolean" -> "false"
            "Bytes" -> "ByteArray(0)"
            "JSON" -> "JsonNull"
            "String", "DateTime", "UUID", "Decimal", "Enum" -> "\"\""
            else -> "error(\"missing selected field ${f.name}\")"
        }
    }

    private fun genSchemaMap(schema: LuxoSchema, pkg: String): String = buildString {
        appendLine("// Auto-generated by luxo. DO NOT EDIT.\n")
        appendLine("package $pkg\n")
        appendLine("import com.luxo.client.APISchemaEntry")
        appendLine("import com.luxo.client.ParamSchema")
        appendLine("import com.luxo.client.SelectionFieldSchema\n")
        appendLine("private val LUXO_SELECTION_TYPES = mapOf(")
        val selectionTypes = schema.types.values.map { it.name to it.fields } +
            schema.models.values.map { it.name to it.fields }
        for ((name, fields) in selectionTypes.sortedBy { it.first }) {
            append("    \"$name\" to mapOf(")
            append(fields.joinToString(", ") { field ->
                val typeName = field.typeName ?: field.type
                val nested = if (isNested(field, schema)) ", \"$typeName\"" else ""
                "\"${field.name}\" to SelectionFieldSchema(${field.id}$nested)"
            })
            appendLine("),")
        }
        appendLine(")\n")
        appendLine("/** API schema map — used by binary transport for encoding requests. */")
        appendLine("val LUXO_SCHEMA: Map<String, APISchemaEntry> = mapOf(")
        for (api in schema.apis.values) {
            if (api.name.startsWith("svc:")) continue
            append("    \"${api.name}\" to APISchemaEntry(${api.id}")
            val returnFields = api.returnType?.let { name ->
                schema.models[name]?.fields ?: schema.types[name]?.fields
            }.orEmpty()
            if (api.params.isNotEmpty() || returnFields.isNotEmpty()) {
                appendLine(", listOf(")
                for (p in api.params) {
                    appendLine("        ParamSchema(${p.id}, \"${p.name}\", \"${p.type}\", isList = ${p.isList}, nullable = ${p.nullable}),")
                }
                append("    )")
            }
            if (returnFields.isNotEmpty()) {
                append(", LUXO_SELECTION_TYPES.getValue(\"${api.returnType}\"), LUXO_SELECTION_TYPES")
            }
            appendLine("),")
        }
        appendLine(")")
    }

    internal fun genClient(schema: LuxoSchema, pkg: String): String = buildString {
        appendLine("// Auto-generated by luxo. DO NOT EDIT.\n")
        appendLine("package $pkg\n")
        appendLine("import com.luxo.client.*")
        appendLine("import kotlinx.serialization.json.*\n")
        appendLine("class LuxoClient(val transport: Transport) {\n")
        appendLine("    init { transport.setSchema(LUXO_SCHEMA) }\n")
        appendLine("    companion object {")
        appendLine("        val schema = LUXO_SCHEMA")
        appendLine("        /** Create client from URL — auto-selects HTTP or WebSocket transport. */")
        appendLine("        fun create(endpoint: String, mode: TransportMode = TransportMode.JSON, token: String? = null): LuxoClient {")
        appendLine("            val transport: Transport = if (endpoint.startsWith(\"ws://\") || endpoint.startsWith(\"wss://\")) {")
        appendLine("                LuxoWebSocket(endpoint, token = token).also {")
        appendLine("                    it.setMode(mode)")
        appendLine("                    it.setSchema(LUXO_SCHEMA)")
        appendLine("                    it.connect()")
        appendLine("                }")
        appendLine("            } else {")
        appendLine("                OkHttpTransport(endpoint, token = token, mode = mode, schema = LUXO_SCHEMA)")
        appendLine("            }")
        appendLine("            return LuxoClient(transport)")
        appendLine("        }")
        appendLine("    }\n")
        appendLine("    fun setMode(mode: TransportMode) = transport.setMode(mode)")
        appendLine("    fun setToken(token: String) = transport.setToken(token)")
        appendLine("    private fun hint(api: String): String? = SelectHints.hints[api]\n")

        for (api in schema.apis.values) {
            if (api.name.startsWith("svc:")) continue
            genMethod(this, api, schema)
        }

        appendLine("}")
    }

    private fun genMethod(b: StringBuilder, api: LuxoAPI, schema: LuxoSchema) {
        val ret = returnType(api)
        val structuredReturn = api.returnType?.let { !isScalar(it) } == true
        if (api.stream) {
            genStreamMethod(b, api, schema, ret)
            genDecodeHelper(b, api)
            return
        }

        // All methods: call transport, then decode based on response type (JSON or binary)
        fun emitDecode() {
            b.appendLine("        return decode_${api.name}(data)")
        }

        // If API has explicit params, always use them (no guessing by name prefix)
        if (api.params.isNotEmpty()) {
            val isPaginated = api.paginated
            val paginationNames = setOf("page", "pageSize")
            // page/pageSize are optional for list APIs
            val ps = api.params.joinToString(", ") {
                val pt = paramKtType(it, schema)
                val forcedOptional = isPaginated && it.name in paginationNames
                when {
                    it.nullable && it.hasDefault -> "${it.name}: LuxoOptional<$pt> = LuxoOptional.Absent"
                    forcedOptional || it.hasDefault -> "${it.name}: $pt? = null"
                    it.nullable -> "${it.name}: $pt?"
                    else -> "${it.name}: $pt"
                }
            }

            fun emitParamAssignments() {
                b.appendLine("        val callParams = mutableMapOf<String, Any?>()")
                for (param in api.params) {
                    val forcedOptional = isPaginated && param.name in paginationNames
                    when {
                        param.nullable && param.hasDefault -> {
                            val value = paramTransportValue(param, schema, "${param.name}.value", nullable = true)
                            b.appendLine("        when (${param.name}) {")
                            b.appendLine("            LuxoOptional.Absent -> Unit")
                            b.appendLine("            is LuxoOptional.Present -> callParams[\"${param.name}\"] = $value")
                            b.appendLine("        }")
                        }
                        forcedOptional || param.hasDefault -> {
                            val value = paramTransportValue(param, schema, nullable = false)
                            b.appendLine("        if (${param.name} != null) callParams[\"${param.name}\"] = $value")
                        }
                        else -> {
                            val value = paramTransportValue(param, schema, nullable = param.nullable)
                            b.appendLine("        callParams[\"${param.name}\"] = $value")
                        }
                    }
                }
            }

            when {
                isPaginated -> {
                    val existingNames = api.params.map { it.name }.toSet()
                    val missingPagination = listOf("page", "pageSize").filter { it !in existingNames }
                    val extraParams = missingPagination.joinToString(", ") { "$it: Long? = null" }
                    val extraParamStr = if (extraParams.isNotEmpty()) ", $extraParams" else ""
                    b.appendLine("    suspend fun ${api.name}($ps$extraParamStr, select: String? = null, filters: List<LuxoFilter>? = null, sorters: List<LuxoSorter>? = null): $ret {")
                    b.appendLine("        val sel = select ?: hint(\"${api.name}\")")
                    emitParamAssignments()
                    for (name in missingPagination) {
                        b.appendLine("        if ($name != null) callParams[\"$name\"] = $name")
                    }
                    b.appendLine("        if (sel != null) callParams[\"\\\$select\"] = sel")
                    b.appendLine("        if (filters != null) callParams[\"\\\$filters\"] = filters.map { mapOf(\"field\" to it.field, \"op\" to it.op, \"value\" to it.value) }")
                    b.appendLine("        if (sorters != null) callParams[\"\\\$sorters\"] = sorters.map { mapOf(\"field\" to it.field, \"order\" to it.order) }")
                    b.appendLine("        val data = transport.call(\"${api.name}\", callParams)")
                    emitDecode()
                    b.appendLine("    }\n")
                }
                structuredReturn -> {
                    b.appendLine("    suspend fun ${api.name}($ps, select: String? = null): $ret {")
                    b.appendLine("        val sel = select ?: hint(\"${api.name}\")")
                    emitParamAssignments()
                    b.appendLine("        if (sel != null) callParams[\"\\\$select\"] = sel")
                    b.appendLine("        val data = transport.call(\"${api.name}\", callParams)")
                    emitDecode()
                    b.appendLine("    }\n")
                }
                // Generic params — all other APIs with explicit params
                else -> {
                    b.appendLine("    suspend fun ${api.name}($ps): $ret {")
                    emitParamAssignments()
                    b.appendLine("        val data = transport.call(\"${api.name}\", callParams)")
                    emitDecode()
                    b.appendLine("    }\n")
                }
            }
        } else {
            when {
                api.paginated -> {
                    b.appendLine("    suspend fun ${api.name}(page: Long? = null, pageSize: Long? = null, select: String? = null, filters: List<LuxoFilter>? = null, sorters: List<LuxoSorter>? = null): $ret {")
                    b.appendLine("        val sel = select ?: hint(\"${api.name}\")")
                    b.appendLine("        val callParams = mutableMapOf<String, Any?>()")
                    b.appendLine("        if (page != null) callParams[\"page\"] = page")
                    b.appendLine("        if (pageSize != null) callParams[\"pageSize\"] = pageSize")
                    b.appendLine("        if (sel != null) callParams[\"\\\$select\"] = sel")
                    b.appendLine("        if (filters != null) callParams[\"\\\$filters\"] = filters.map { mapOf(\"field\" to it.field, \"op\" to it.op, \"value\" to it.value) }")
                    b.appendLine("        if (sorters != null) callParams[\"\\\$sorters\"] = sorters.map { mapOf(\"field\" to it.field, \"order\" to it.order) }")
                    b.appendLine("        val data = transport.call(\"${api.name}\", callParams)")
                    emitDecode()
                    b.appendLine("    }\n")
                }
                structuredReturn -> {
                    b.appendLine("    suspend fun ${api.name}(select: String? = null): $ret {")
                    b.appendLine("        val sel = select ?: hint(\"${api.name}\")")
                    b.appendLine("        val callParams = mutableMapOf<String, Any?>()")
                    b.appendLine("        if (sel != null) callParams[\"\\\$select\"] = sel")
                    b.appendLine("        val data = transport.call(\"${api.name}\", callParams)")
                    emitDecode()
                    b.appendLine("    }\n")
                }
                else -> {
                    b.appendLine("    suspend fun ${api.name}(): $ret {")
                    b.appendLine("        val data = transport.call(\"${api.name}\")")
                    emitDecode()
                    b.appendLine("    }\n")
                }
            }
        }

        // Private decode helper — dispatches JSON vs binary
        genDecodeHelper(b, api)
    }

    private fun genStreamMethod(b: StringBuilder, api: LuxoAPI, schema: LuxoSchema, returnType: String) {
        val params = api.params.map { param ->
            val type = paramKtType(param, schema)
            when {
                param.nullable && param.hasDefault -> "${param.name}: LuxoOptional<$type> = LuxoOptional.Absent"
                param.hasDefault -> "${param.name}: $type? = null"
                param.nullable -> "${param.name}: $type?"
                else -> "${param.name}: $type"
            }
        }.toMutableList()
        val structuredReturn = api.returnType?.let { !isScalar(it) } == true
        if (structuredReturn) params += "select: String? = null"
        val separator = if (params.isEmpty()) "" else "${params.joinToString(", ")}, "
        val methodName = "subscribe" + api.name.replaceFirstChar { it.uppercase() }
        b.appendLine("    suspend fun $methodName(${separator}onData: ($returnType) -> Unit): () -> Unit {")
        b.appendLine("        val callParams = mutableMapOf<String, Any?>()")
        for (param in api.params) {
            val value = paramTransportValue(param, schema, nullable = param.nullable)
            when {
                param.nullable && param.hasDefault -> {
                    val optionalValue = paramTransportValue(param, schema, "${param.name}.value", nullable = true)
                    b.appendLine("        when (${param.name}) {")
                    b.appendLine("            LuxoOptional.Absent -> Unit")
                    b.appendLine("            is LuxoOptional.Present -> callParams[\"${param.name}\"] = $optionalValue")
                    b.appendLine("        }")
                }
                param.hasDefault -> b.appendLine("        if (${param.name} != null) callParams[\"${param.name}\"] = $value")
                else -> b.appendLine("        callParams[\"${param.name}\"] = $value")
            }
        }
        if (structuredReturn) b.appendLine("        if (select != null) callParams[\"\\\$select\"] = select")
        b.appendLine("        return transport.subscribe(\"${api.name}\", callParams) { data ->")
        b.appendLine("            onData(decode_${api.name}(data))")
        b.appendLine("        }")
        b.appendLine("    }\n")
    }

    private fun genDecodeHelper(b: StringBuilder, api: LuxoAPI) {
        val ret = returnType(api)
        val t = api.returnType
        b.appendLine("    private fun decode_${api.name}(data: Any): $ret = when (data) {")

        if (t == null || isScalar(t)) {
            // Scalar decode
            val jsonScalarDecode = when (t) {
                    null, "Int", "Duration" -> "(data as JsonElement).jsonPrimitive.long"
                "Float" -> "(data as JsonElement).jsonPrimitive.double"
                "Boolean" -> "(data as JsonElement).jsonPrimitive.boolean"
                "Bytes" -> "java.util.Base64.getDecoder().decode((data as JsonElement).jsonPrimitive.content)"
                "JSON" -> "data as JsonElement"
                else -> "(data as JsonElement).jsonPrimitive.content"
            }
            val binaryScalarDecode = when (t) {
                    null, "Int", "Duration" -> "LuxoDecoder(data).readInt()"
                "Float" -> "LuxoDecoder(data).readFloat()"
                "Boolean" -> "LuxoDecoder(data).readBool()"
                "DateTime" -> "LuxoDecoder(data).readDateTime()"
                "UUID" -> "LuxoDecoder(data).readUuid()"
                "Bytes" -> "LuxoDecoder(data).readBytes()"
                "JSON" -> "Json.parseToJsonElement(LuxoDecoder(data).readBytes().toString(Charsets.UTF_8))"
                else -> "LuxoDecoder(data).readString()"
            }
            val jsonDecode = if (api.returnList) {
                when (t) {
                        null, "Int", "Duration" -> "(data as JsonArray).map { it.jsonPrimitive.long }"
                    "Float" -> "(data as JsonArray).map { it.jsonPrimitive.double }"
                    "Boolean" -> "(data as JsonArray).map { it.jsonPrimitive.boolean }"
                    "Bytes" -> "(data as JsonArray).map { java.util.Base64.getDecoder().decode(it.jsonPrimitive.content) }"
                    "JSON" -> "(data as JsonArray).toList()"
                    else -> "(data as JsonArray).map { it.jsonPrimitive.content }"
                }
            } else jsonScalarDecode
            val binaryDecode = if (api.returnList) {
                val element = scalarElementRead(t ?: "Int", "d")
                "LuxoDecoder(data).let { d -> d.readArray { $element } }"
            } else binaryScalarDecode
            b.appendLine("        is ByteArray -> $binaryDecode")
            b.appendLine("        else -> $jsonDecode")
        } else {
            // Model decode
            val jsonDecode = when {
                api.paginated -> "(data as JsonElement).jsonObject.let { obj -> Page(obj[\"items\"]!!.jsonArray.map { decodeJSON$t(it.jsonObject) }, obj[\"total\"]!!.jsonPrimitive.int, obj[\"page\"]!!.jsonPrimitive.int, obj[\"pageSize\"]!!.jsonPrimitive.int) }"
                api.returnList -> "(data as JsonArray).map { decodeJSON$t(it.jsonObject) }"
                else -> "decodeJSON$t((data as JsonElement).jsonObject)"
            }
            val binaryDecode = when {
                api.paginated -> "decodePaginated$t(data)"
                api.returnList -> "decodeColumnar$t(data)"
                else -> "decode$t(LuxoDecoder(data))"
            }
            b.appendLine("        is ByteArray -> $binaryDecode")
            b.appendLine("        else -> $jsonDecode")
        }

        b.appendLine("    }\n")
    }

    private fun returnType(api: LuxoAPI): String {
        val returnType = api.returnType ?: return "Long"
        val t = luxoTypeToKt(returnType)
        return when {
            api.paginated -> "Page<$t>"
            api.returnList -> "List<$t>"
            else -> t
        }
    }
}

/** CLI entry point for gradle JavaExec task. */
object LuxoCodegenCli {
    @JvmStatic
    fun main(args: Array<String>) {
        require(args.isNotEmpty()) { "Usage: LuxoCodegenCli <endpoint> [outDir] [package] [schemaFile]" }
        val endpoint = args[0]
        val key = System.getenv("LUXO_INTROSPECTION_KEY").orEmpty()
        val outDir = args.getOrElse(1) { "src/main/kotlin/com/luxo/generated" }
        val pkg = args.getOrElse(2) { "com.luxo.generated" }
        val schemaFile = args.getOrNull(3)
        LuxoCodegen.generate(endpoint, key, outDir, pkg, schemaFile)
    }
}
