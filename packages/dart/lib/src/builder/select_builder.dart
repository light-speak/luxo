import 'dart:async';

import 'package:build/build.dart';
import 'package:analyzer/dart/ast/ast.dart';
import 'package:glob/glob.dart';

// source_gen not needed — using build runner directly
import 'select_analyzer.dart';

/// Build runner builder that scans user code for LuxoClient API calls,
/// traces field access, and generates _select_hints.g.dart.
///
/// Usage in build.yaml:
/// ```yaml
/// targets:
///   $default:
///     builders:
///       luxo_client|select_hints:
///         enabled: true
/// ```
class SelectHintsBuilder implements Builder {
  /// Model field type map from generated types (populated from schema)
  final Map<String, Map<String, String>> modelFields;

  SelectHintsBuilder(this.modelFields);

  @override
  Map<String, List<String>> get buildExtensions => {
    r'lib/$lib$': ['lib/src/luxo/_select_hints.g.dart'],
  };

  @override
  Future<void> build(BuildStep buildStep) async {
    final allHints = <String, FieldNode>{};
    final visited = <Uri>{};
    final inputs = await buildStep.findAssets(Glob('lib/**.dart')).toList();
    inputs.sort((a, b) => a.path.compareTo(b.path));
    // Resolve each library once; its fragments also include part files.
    for (final input in inputs) {
      if (input.path.endsWith('.g.dart')) continue;
      if (!await buildStep.resolver.isLibrary(input)) continue;
      await _analyzeLibrary(buildStep, input, visited, allHints);
    }

    final output = AssetId(
      buildStep.inputId.package,
      'lib/src/luxo/_select_hints.g.dart',
    );

    final code = StringBuffer();
    code.writeln('// GENERATED BY luxo_client. DO NOT EDIT.');
    code.writeln('// Rebuild with: dart run build_runner build\n');
    code.writeln('/// Field access hints — auto-detected from your code.');
    code.writeln(
      '/// Used by LuxoClient to inject \$select for optimal queries.',
    );
    code.writeln('const selectHints = <String, String>{');
    final names = allHints.keys.toList()..sort();
    for (final name in names) {
      final select = allHints[name]!.toSelectString();
      if (select.isEmpty) continue;
      code.writeln("  '$name': '$select',");
    }
    code.writeln('};');

    await buildStep.writeAsString(output, code.toString());
  }

  Future<void> _analyzeLibrary(
    BuildStep step,
    AssetId input,
    Set<Uri> visited,
    Map<String, FieldNode> hints,
  ) async {
    final library = await step.resolver.libraryFor(input);
    for (final fragment in library.fragments) {
      final uri = fragment.source.uri;
      if (uri.path.endsWith('.g.dart') || !visited.add(uri)) continue;
      final unit = await step.resolver.astNodeFor(fragment, resolve: true);
      if (unit is! CompilationUnit) {
        throw StateError('Cannot resolve Luxo field selections in $uri');
      }
      final analyzer = SelectAnalyzer(
        modelFields,
        clientLibrary: Uri.parse(
          'package:${step.inputId.package}/src/luxo/client.dart',
        ),
      );
      unit.accept(analyzer);
      for (final entry in analyzer.hints.entries) {
        hints.putIfAbsent(entry.key, FieldNode.root).merge(entry.value);
      }
    }
  }
}

/// Factory for build_runner registration.
Builder selectHintsBuilder(BuilderOptions options) {
  // Generated Selected<T> fields supply model metadata from resolved types.
  return SelectHintsBuilder(<String, Map<String, String>>{});
}
