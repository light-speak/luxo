part of 'codegen.dart';

void _queryIdentifier(String name) {
  if (!RegExp(r'^[A-Za-z_][A-Za-z0-9_]*$').hasMatch(name)) {
    throw FormatException('invalid query identifier: $name');
  }
}

List<String> _queryOperators(String type, bool isEnum) {
  if (isEnum || type == 'Boolean' || type == 'UUID') return ['eq', 'ne'];
  if (type == 'String')
    return ['eq', 'ne', 'contains', 'startswith', 'endswith', 'match'];
  if (['Int', 'Float', 'DateTime', 'Decimal'].contains(type))
    return ['eq', 'ne', 'gt', 'gte', 'lt', 'lte'];
  throw FormatException('unsupported query type: $type');
}

/// Builds only API-advertised controls; it never infers capabilities from a return model.
String generateQueryBuilders(LuxoSchema schema) {
  final b = StringBuffer("// Code generated by luxo. DO NOT EDIT.\n");
  if (schema.apis.values.any(
    (api) =>
        !api.internal &&
        api.query != null &&
        (api.query!.filters.isNotEmpty || api.query!.sorters.isNotEmpty),
  )) {
    b.writeln("import 'package:luxo_client/luxo_client.dart';");
  }
  final needsEnums = schema.apis.values.any(
    (api) =>
        !api.internal &&
        (api.query?.filters.any((f) => schema.enums.containsKey(f.type)) ??
            false),
  );
  if (needsEnums) b.writeln("import 'types.dart';");
  for (final api in schema.apis.values) {
    if (api.internal || api.query == null) continue;
    _queryIdentifier(api.name);
    final generatedName = 'LuxoQuery_${api.name}';
    if (schema.models.containsKey(generatedName) ||
        schema.types.containsKey(generatedName) ||
        schema.enums.containsKey(generatedName)) {
      throw FormatException(
        'query builder conflicts with declared type: $generatedName',
      );
    }
    if (!api.paginated || api.stream)
      throw FormatException(
        'query controls require a paginated unary API: ${api.name}',
      );
    b.writeln('abstract final class LuxoQuery_${api.name} {');
    _writeQueryFilters(b, api.query!.filters, schema);
    _writeQuerySorters(b, api.query!.sorters);
    b.writeln('}');
  }
  return b.toString();
}

void _writeQueryFilters(
  StringBuffer b,
  List<LuxoQueryFilter> filters,
  LuxoSchema schema,
) {
  final names = <String>{};
  for (final field in filters) {
    _queryIdentifier(field.field);
    _queryIdentifier(field.type);
    if (!names.add(field.field))
      throw FormatException('duplicate query field: ${field.field}');
    final isEnum = schema.enums.containsKey(field.type);
    final allowed = _queryOperators(field.type, isEnum);
    final seen = <String>{};
    if (field.operators.isEmpty)
      throw FormatException('empty query operators: ${field.field}');
    for (final op in field.operators) {
      if (!allowed.contains(op) || !seen.add(op))
        throw FormatException('invalid query operator: $op');
      final type = isEnum ? field.type : _luxoTypeToDart(field.type);
      final value = isEnum ? 'value.rawValue' : 'value';
      b.writeln(
        "  static LuxoFilter ${field.field}_$op($type value) => LuxoFilter(field: '${field.field}', op: '$op', value: $value);",
      );
    }
  }
}

void _writeQuerySorters(StringBuffer b, List<String> sorters) {
  final names = <String>{};
  for (final field in sorters) {
    _queryIdentifier(field);
    if (!names.add(field))
      throw FormatException('duplicate sorter field: $field');
    for (final order in ['asc', 'desc']) {
      b.writeln(
        "  static LuxoSorter ${field}_$order() => LuxoSorter(field: '$field', order: '$order');",
      );
    }
  }
}
